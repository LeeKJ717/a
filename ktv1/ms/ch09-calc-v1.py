def otsu(vs):
    n = len(vs); best = None; rows = []
    for t in range(min(vs), max(vs)):
        a = [v for v in vs if v <= t]; b = [v for v in vs if v > t]
        w0, w1 = len(a) / n, len(b) / n
        m0, m1 = sum(a) / len(a), sum(b) / len(b)
        sb = w0 * w1 * (m0 - m1) ** 2
        rows.append((t, w0, w1, m0, m1, sb))
        if best is None or sb > best[5]: best = rows[-1]
    return rows, best
