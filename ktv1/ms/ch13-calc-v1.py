def hdr(s): print('\n' + '=' * 8, s)
def pct(a, b): return 100.0 * a / b
def bc(calbp, base=1950): return base - calbp
def fy(y):
    y = round(y)
    return ('기원전 %d년' % (-y)) if y <= 0 else ('서기 %d년' % y)
def inter(a, b):
    lo, hi = max(a[0], b[0]), min(a[1], b[1])
    return (lo, hi, hi - lo) if hi >= lo else None

