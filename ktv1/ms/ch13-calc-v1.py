def hav(lo1, la1, lo2, la2):
    Rr = 6371.0088
    p1, p2 = radians(la1), radians(la2)
    dl = radians(lo2 - lo1)
    a = sin((p2 - p1) / 2) ** 2 + cos(p1) * cos(p2) * sin(dl / 2) ** 2
    return 2 * Rr * asin(sqrt(a))
