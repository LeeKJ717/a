p, q = osl[0], osl[1]    # 142 cm 와 255 cm
def var_dt(rho):
    t1 = p[3] / p[1]; t2 = q[3] / q[1]
    a1 = p[4] / p[1]; a2 = q[4] / q[1]                 # De 오차 기여
    b1 = p[3] * p[2] / p[1] ** 2; b2 = q[3] * q[2] / q[1] ** 2   # 선량률 오차 기여
    return a1 ** 2 + a2 ** 2 + b1 ** 2 + b2 ** 2 - 2 * rho * b1 * b2, (t1, t2, a1, a2, b1, b2)
for rho in (0.0, 0.5, 1.0):
    v, (t1, t2, a1, a2, b1, b2) = var_dt(rho)
    print(f'  rho={rho}: sigma(t2-t1) = {math.sqrt(v):.3f} ka (t2-t1 = {t2-t1:.3f} ka; De 기여 {math.hypot(a1,a2):.3f}, 선량률 기여 {math.sqrt(b1**2+b2**2-2*rho*b1*b2):.3f})')
print('  제1권 6장 계산 6-2 는 표의 나이 오차(0.4, 0.4)를 합쳐 0.57 을 썼다 (독립 가정, De 와 선량률 오차를 모두 담은 값).')
print('  rho 가 클수록 나이 차의 오차는 줄어든다(각 나이의 오차는 그대로). 선량률 오차 가운데 시료끼리 공유하는 몫은 논문이 밝혀야 알 수 있다(원문 확인 필요). 이 줄의 rho 는 시연값이다.')
# 몬테카를로 확인
