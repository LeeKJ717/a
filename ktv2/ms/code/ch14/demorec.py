# -*- coding: utf-8 -*-
"""demorec: 14장 시연 레코드. 이름, 구절, 좌표가 모두 가상이다.
실제 사료에서 가져온 것이 하나도 없다. 구절은 모두 '[가상]'으로 시작하고 status 는 '시연'이다.
좌표(경도, 위도)는 지도 배경 없이 구조만 보이려고 임의로 잡은 시연값이며 실제 땅과 무관하다.
거리 환산 1리 = 0.4 km 는 시연값이다(실제 환산은 시대와 문헌마다 다르며 확인 필요)."""
import placekit as P


def load(con):
    ids = {}
    w1 = P.add_work(con, '가상지리지', None, '지리지', '14장 시연용 가상 문헌', 1)
    w2 = P.add_work(con, '시연실록', None, '실록', '14장 시연용 가상 문헌', 1)
    e1 = P.add_edition(con, w1, '가상 갑본', '미확인', '가상', '시연용 가상 판본', 1)
    e2 = P.add_edition(con, w1, '가상 을본', '미확인', '가상', '시연용 가상 판본', 1)
    e3 = P.add_edition(con, w2, '가상 갑본', '미확인', '가상', '시연용 가상 판본', 1)
    s1 = P.add_section(con, w1, '권1', '주군편(가상)')
    s2 = P.add_section(con, w1, '권2', '산천편(가상)')
    s3 = P.add_section(con, w2, '권7', None)
    ids['ed'] = (e1, e2, e3)
    pas = {}

    def ps(key, sec, ed, text, date_text, y0, y1, **kw):
        pas[key] = P.add_passage(con, sec, ed, '시연', text=text, date_text=date_text, year_from=y0, year_to=y1, is_demo=1, **kw)
    ps('a1', s1, e1, '[가상] 가상성은 시연산 남쪽에 있다.', '가상 1기', 150, 150)
    ps('a2', s1, e1, '[가상] 가상성을 옮겨 시연강 가에 새로 쌓았다.', '가상 2기', 400, 400)
    ps('a3', s3, e3, '[가상] 가상성 안에 객관을 두었다.', '가상 3기', 700, 700)
    ps('b1', s2, e1, '[가상] 견본나루는 가상성 동쪽 삼십 리에 있다.', '가상 2기', 450, 450, collation='교감중', collation_note='을본은 삼백 리로 적었다(가상)')
    ps('c1', s1, e1, '[가상] 예시고을은 북쪽 변방의 고을이다.', '가상 1기', 160, 160)
    ps('c2', s3, e3, '[가상] 예시고을에 가뭄이 들었다.', '가상 2기', 500, 500)
    ps('d1', s1, e1, '[가상] 가상포는 나루가 있어 배가 닿는다.', '가상 1기', 200, 200)
    ps('d2', s1, e1, '[가상] 가상포의 나루를 넓혔다.', '가상 2기', 450, 450)
    ps('d3', s3, e3, '[가상] 가상포에 창고를 세웠다.', '가상 3기', 800, 800)
    ps('f1', s2, e1, '[가상] 이름뿐성은 오래된 성이라 한다.', '가상 1기', 180, 180)
    ps('g1', s2, e1, '[가상] 표본천은 맑은 내이다.', '가상 1기', 190, 190)
    ps('g2', s2, e1, '[가상] 표본산은 높은 산이다.', '가상 1기', 190, 190)
    P.get_or_add(con, 'variant', ['passage_id', 'edition_id'], dict(passage_id=pas['b1'], edition_id=e2, reading='[가상] 견본나루는 가상성 동쪽 삼백 리에 있다.', diff_note='삼십/삼백 (가상 이문)'))
    ids['pas'] = pas
    v_b1 = con.execute('SELECT variant_id FROM variant WHERE passage_id=?', (pas['b1'],)).fetchone()[0]
    ids['v_b1'] = v_b1

    E1 = P.add_era(con, '가상 1기', 100, 299, '14장 시연')
    E2 = P.add_era(con, '가상 2기', 300, 599, '14장 시연')
    E3 = P.add_era(con, '가상 3기', 600, 899, '14장 시연')
    ne = {}
    names = {k: P.add_name(con, k, '옛지명', None, 1) for k in ['가상성', '시연포', '예시고을', '견본나루', '가상포', '이름뿐성', '표본천', '표본산', '시기어긋성', '한출처성']}

    def NE(nm, era):
        k = (nm, era)
        if k not in ne:
            ne[k] = P.add_ne(con, names[nm], {1: E1, 2: E2, 3: E3}[era])
        return ne[k]
    ids['ne'] = ne
    for nm, era, key in [('가상성', 1, 'a1'), ('가상성', 2, 'a2'), ('가상성', 3, 'a3'), ('견본나루', 2, 'b1'), ('예시고을', 1, 'c1'), ('예시고을', 2, 'c2'),
                         ('가상포', 1, 'd1'), ('가상포', 2, 'd2'), ('가상포', 3, 'd3'), ('이름뿐성', 1, 'f1'), ('표본천', 1, 'g1'), ('표본산', 1, 'g2')]:
        P.add_att(con, NE(nm, era), pas[key])
    for e in (1, 2, 3):
        NE('시연포', e)            # 구절 없이 후보만 두는 경우

    cand = {}

    def C(key, nm, era, lon, lat, r, level, claimed, modern, origin='시연값', **kw):
        cand[key] = P.add_cand(con, NE(nm, era), level, origin, modern, lon, lat, r, '14장 시연', None, claimed, is_demo=1, **kw)
        return cand[key]
    # 1) 가상성: 1기와 2기는 160 km 떨어지고 2기와 3기는 2~3 km
    C('gs1', '가상성', 1, 20.00, 6.00, 5, '점', 'A', '가상 갑 지점')
    P.add_ev(con, cand['gs1'], '원문방향거리', '가상사료', '지지', '가상지리지 권1', pas['a1'])
    P.add_ev(con, cand['gs1'], '좌표', '가상논문1', '지지', '가상논문1 표 1(가상)')
    P.add_ev(con, cand['gs1'], '지형고고', '가상조사2', '지지', '가상 발굴 보고(가상)')
    C('gs2', '가상성', 2, 21.50, 6.00, 5, '점', 'B', '가상 을 지점')
    P.add_ev(con, cand['gs2'], '원문방향거리', '가상사료', '지지', '가상지리지 권1', pas['a2'])
    P.add_ev(con, cand['gs2'], '현대지명대응', '가상논문1', '지지', '가상논문1 본문(가상)')
    C('gs3', '가상성', 3, 21.52, 6.01, 5, '점', 'C', '가상 을 지점 곁')
    P.add_ev(con, cand['gs3'], '현대지명대응', '가상논문3', '지지', '가상논문3(가상)')
    # 2) 시연포: 세 시대 모두 같은 곳
    C('sp1', '시연포', 1, 20.50, 7.00, 8, '점', 'B', '가상 병 지점')
    P.add_ev(con, cand['sp1'], '좌표', '가상논문4', '지지', '가상논문4(가상)'); P.add_ev(con, cand['sp1'], '지형고고', '가상조사5', '지지', '가상 조사(가상)')
    C('sp2', '시연포', 2, 20.51, 7.01, 8, '점', 'B', '가상 병 지점')
    P.add_ev(con, cand['sp2'], '좌표', '가상논문4', '지지', '가상논문4(가상)'); P.add_ev(con, cand['sp2'], '지형고고', '가상조사5', '지지', '가상 조사(가상)')
    C('sp3', '시연포', 3, 20.50, 7.02, 8, '점', 'C', '가상 병 지점')
    P.add_ev(con, cand['sp3'], '좌표', '가상논문4', '지지', '가상논문4(가상)')
    # 3) 예시고을: 1기 현 수준 후보(좌표 있음), 2기 현 이름만(좌표 없음), 3기 후보 없음
    C('ey1', '예시고을', 1, 22.00, 5.50, 30, '현', 'C', '가상 정 현')
    P.add_ev(con, cand['ey1'], '현대지명대응', '가상논문6', '지지', '가상논문6(가상)')
    cand['ey2'] = P.add_cand(con, NE('예시고을', 2), '현', '없음', '가상 정 현 북부', None, None, None, '가상논문6', '좌표 없음: 찍지 않는다', 'C', is_demo=1)
    P.add_ev(con, cand['ey2'], '현대지명대응', '가상논문6', '지지', '가상논문6(가상)')
    NE('예시고을', 3)
    # 4) 견본나루: 가상성 동쪽 30리(=12 km) 또는 300리(=120 km) 이문
    C('gn', '견본나루', 2, 21.61, 6.00, 1, '점', 'C', '가상 을 지점 동쪽')
    P.add_ev(con, cand['gn'], '원문방향거리', '가상사료', '지지', '가상지리지 권2', pas['b1'])
    ids['rel_b'] = {}
    ids['rel_b']['main'] = P.add_rel(con, pas['b1'], '가상지리지 권2', NE('가상성', 2), NE('견본나루', 2), '방향거리', 90.0, 22.5, 12.0, 2.0, None, '동쪽(8방위 서술), 30리=12 km(시연 환산)')
    ids['rel_b']['alt'] = P.add_rel(con, pas['b1'], '가상지리지 권2', NE('가상성', 2), NE('견본나루', 2), '방향거리', 90.0, 22.5, 120.0, 20.0, v_b1, '동쪽, 300리=120 km(을본 읽기)')
    # 5) 가상포: 반경 60 km, 간격 약 100 km 의 사슬
    C('gp1', '가상포', 1, 23.00, 5.00, 60, '지역', 'C', '가상 무 지역')
    C('gp2', '가상포', 2, 23.90, 5.00, 60, '지역', 'C', '가상 무 지역 동쪽')
    C('gp3', '가상포', 3, 24.80, 5.00, 60, '지역', 'C', '가상 무 지역 더 동쪽')
    for k in ('gp1', 'gp2', 'gp3'):
        P.add_ev(con, cand[k], '현대지명대응', '가상논문7', '지지', '가상논문7(가상)')
    # 6) 이름뿐성 1기: 이름 일치 증거뿐인데 B 로 신고
    C('nm', '이름뿐성', 1, 22.50, 7.50, 30, '현', 'B', '가상 기 현')
    P.add_ev(con, cand['nm'], '이름일치', '이름', '지지', '이름이 같다는 것뿐')
    # 7) 같은 좌표의 서로 다른 이름
    C('t1', '표본천', 1, 22.80, 6.20, 1, '점', 'C', '가상 경 지점', origin='논문본문')
    C('t2', '표본산', 1, 22.80, 6.20, 1, '점', 'C', '가상 경 지점', origin='논문본문')
    P.add_ev(con, cand['t1'], '좌표', '가상논문8', '지지', '가상논문8 표 2(가상)'); P.add_ev(con, cand['t2'], '좌표', '가상논문8', '지지', '가상논문8 표 2(가상)')
    # 8) 시기 창이 어긋난 후보(2기 창 300~599, 후보가 가리키는 시기 700~750)
    cand['gs2w'] = P.add_cand(con, NE('시기어긋성', 2), '점', '시연값', '가상 임 지점', 24.00, 8.00, 5, '14장 시연', '시기 어긋남 시연', 'C', valid_from=700, valid_to=750, is_demo=1)
    P.add_ev(con, cand['gs2w'], '현대지명대응', '가상논문9', '지지', '가상논문9(가상)')
    # 9) 같은 논문에서 나온 증거 셋: 종류는 셋이나 독립 출처는 하나
    C('one', '한출처성', 2, 22.60, 7.60, 30, '현', 'A', '가상 신 현')
    for t in ('원문방향거리', '좌표', '현대지명대응'):
        P.add_ev(con, cand['one'], t, '가상논문10', '지지', '가상논문10(가상) 같은 논문의 세 곳')
    ids['cand'] = cand
    con.commit()
    return ids
