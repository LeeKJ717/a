# -*- coding: utf-8 -*-
"""0장 점검: 제1권 계산 11 스크립트의 실행 로그와 제1권 원고(ch11-v1.md)가 같은 값을 말하는지 대조한다.
사용: python verify-vol1-v1.py 실행로그 제1권원고
각 항목은 (이름, 로그에 있어야 할 글, 원고에 있어야 할 글)이다. 두 글이 모두 있으면 일치로 센다.
이 검사는 값의 '문자열'이 양쪽에 있는지만 본다. 같은 문맥의 값인지는 사람이 읽어 확인한다(본문 0.8절)."""
import sys
log = open(sys.argv[1], encoding='utf-8').read()
ms = open(sys.argv[2], encoding='utf-8').read()
CHECKS = [
    ('계산 11-3 Fisher 양쪽 p(신석기 대 청동기)', 'p = 0.00079', '0.00079'),
    ('계산 11-3 Fisher 양쪽 p(대전자)', 'p = 0.19368', '0.194'),
    ('계산 11-3b 양쪽 p 합산', '7.899276e-04', '7.90 × 10⁻⁴'),
    ('계산 11-4 H 신석기 합', 'H = 0.2157', '0.2157'),
    ('계산 11-4 H 대산전', 'H = 0.8611', '0.8611'),
    ('계산 11-4 부트스트랩 신석기 합 97.5%', '97.5% 0.464', '0.000~0.464(중앙 0.209)'),
    ('계산 11-4 부트스트랩 대산전 하한', '2.5% 0.556', '0.556~0.889(중앙 0.778)'),
    ('계산 11-5 F 통계', '75.163', '75.16'),
    ('계산 11-6 부호 검정 (20, 9) 양쪽 p', '0.0614', '0.061'),
    ('계산 11-9 유효 표본 n_eff', '131.3', '131.3'),
    ('계산 11-11 한 변이의 햇수', '1333.3년', '1333.3년'),
    ('계산 11-12 순열 4개의 최소 P', '0.0417', '0.0417'),
    ('계산 11-13 노백산-돈화 거리', '82.43 km', '82.43 km'),
    ('계산 11-14 EPS 0.85에 필요한 나무 수', '20.09', '20.09'),
]
ok = 0
for name, a, b in CHECKS:
    ia, ib = a in log, b in ms
    st = '일치' if (ia and ib) else ('로그에 없음' if not ia else '원고에 없음')
    ok += (ia and ib)
    print('%-36s 로그[%s] 원고[%s] -> %s' % (name, a, b, st))
print('일치 %d / %d' % (ok, len(CHECKS)))
sys.exit(0 if ok == len(CHECKS) else 1)
