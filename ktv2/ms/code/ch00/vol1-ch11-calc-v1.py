hdr('계산 11-4 Nei 유전자 다양도 H = n/(n-1) (1 - sum p^2) (하플로그룹 수준)')
def nei(c):
    n = sum(c)
    if n < 2: return float('nan')
    return n / (n - 1) * (1 - sum((x / n) ** 2 for x in c))
