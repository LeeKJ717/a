def boot(c, B=20000):
    n = sum(c); pr = np.array(c) / n
    hs = []
    for _ in range(B):
        k = rng.multinomial(n, pr)
        hs.append(nei([int(x) for x in k if x > 0]) if n > 1 else 0)
    hs = np.array([h for h in hs if not math.isnan(h)])
    return np.percentile(hs, [2.5, 50, 97.5])
