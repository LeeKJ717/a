hdr('계산 11-3 Fisher 정확검정 (직접 구현, scipy와 대조)')
def hyp(a, b, c, d):
    n = a + b + c + d
    return comb(a + b, a) * comb(c + d, c) / comb(n, a + c)
def fisher2(a, b, c, d, alt='two'):
    n = a + b + c + d
    r1, r2, c1 = a + b, c + d, a + c
    lo, hi = max(0, c1 - r2), min(r1, c1)
    p0 = hyp(a, b, c, d)
    ps = {x: comb(r1, x) * comb(r2, c1 - x) / comb(n, c1) for x in range(lo, hi + 1)}
    if alt == 'two':
        return sum(p for p in ps.values() if p <= p0 * (1 + 1e-9))
    if alt == 'greater':
        return sum(p for x, p in ps.items() if x >= a)
    return sum(p for x, p in ps.items() if x <= a)
print('검증: 위키백과 예 [[1,9],[11,3]] 한쪽 p =', '%.9f' % fisher2(1, 9, 11, 3, 'less'), '(위키 0.001379728)')
print('       그 표 자신의 확률 =', '%.9f' % hyp(1, 9, 11, 3), '(위키 0.001346076)', ' 더 극단 [[0,10],[12,2]] =', '%.9f' % hyp(0, 10, 12, 2), '(위키 0.000033652)')
