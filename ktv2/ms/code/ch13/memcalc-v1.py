"""모델 가중치만의 메모리 = 매개변수 수 x 비트 수 / 8. 이 책의 산술이며 실측이 아니다.
문맥 길이에 따른 캐시, 실행 프로그램의 여유, 양자화 형식별 실제 평균 비트 수는 넣지 않았다(확인 필요)."""
GIB = 2 ** 30
print('매개변수(십억)  16비트    8비트    4비트   (가중치만, GiB)')
for b in (1, 3, 7, 14, 32):
    p = b * 1e9
    print('%8d       %7.2f  %7.2f  %7.2f' % (b, p * 16 / 8 / GIB, p * 8 / 8 / GIB, p * 4 / 8 / GIB))
print('이 컨테이너 RAM 8 GiB (실제로 쓸 수 있는 양은 free -m 의 available 6669 MiB = %.2f GiB)' % (6669 / 1024))
print('이 책의 기준 그래픽 메모리 12 GB급(10장). 12 GB = %.2f GiB' % (12e9 / GIB))
