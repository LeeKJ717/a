# -*- coding: utf-8 -*-
"""계산 13-5: 어느 쪽 숫자를 더 믿어야 하는가. 경계 연대 쪽(10,700 ± 모형 오차)과 점 쪽(10,304 ± 56 ± 체계 오차)을 역분산 가중평균으로 합친다.
가정: 두 숫자가 같은 사건(H4/H3 경계)의 연대를 독립으로 재고 있다. 점이 경계의 연대를 직접 재고 있다는 가정이 들어 있다(시료가 경계 바로 위에 있고 두께가 0.5 cm).
점 쪽 체계 오차(현대 탄소 혼입, 저장 효과 등 측정 오차에 들어 있지 않은 것)는 알 수 없으므로 0, 100, 200, 340, 500년을 시연값으로 놓는다.
경계 쪽 오차는 계산 13-2 의 가정 (다) 229, (라) 339, (마) 742 년을 쓴다.
"""
import numpy as np
A, SA = 10304.0, 56.0     # 점
B = 10700.0               # 경계
print('=== 계산 13-5 (1) 역분산 가중평균: 경계 쪽 오차 x 점 쪽 체계 오차 ===')
print('%-22s %-12s | %8s %6s %10s' % ('경계 쪽 오차(년)', '점 쪽 체계 오차', '합친 연대', 'sd', '점의 가중 비율'))
rows = []
for sb in (229.0, 339.0, 742.0):
    for ss in (0.0, 100.0, 200.0, 340.0, 500.0):
        va = SA ** 2 + ss ** 2; vb = sb ** 2
        wa, wb = 1 / va, 1 / vb
        m = (wa * A + wb * B) / (wa + wb); sd = np.sqrt(1 / (wa + wb))
        rows.append(dict(sb=sb, ss=ss, mean=float(m), sd=float(sd), wa=float(wa / (wa + wb))))
        print('%-22.0f %-12.0f | %8.0f %6.0f %9.1f%%' % (sb, ss, m, sd, wa / (wa + wb) * 100))
print('\n=== 계산 13-5 (2) 점과 경계가 같은 비중이 되는 점 쪽 체계 오차 ===')
for sb in (229.0, 339.0, 742.0):
    ss = np.sqrt(max(sb ** 2 - SA ** 2, 0.0))
    print('경계 쪽 오차 %.0f 년이면 점 쪽 총오차가 %.0f 년(= 체계 오차 %.0f 년과 측정 오차 56 년의 합성)일 때 두 숫자의 비중이 같다' % (sb, sb, ss))
print('\n=== 계산 13-5 (3) 손으로 따라 하는 숫자 ===')
print('56^2 = %d, 229^2 = %d, 합 %d, 제곱근 %.2f, 396/제곱근 = %.2f' % (56 ** 2, 229 ** 2, 56 ** 2 + 229 ** 2, np.sqrt(56 ** 2 + 229 ** 2), 396 / np.sqrt(56 ** 2 + 229 ** 2)))
print('339^2 = %d, 합 %d, 제곱근 %.2f, 396/제곱근 = %.2f' % (339 ** 2, 56 ** 2 + 339 ** 2, np.sqrt(56 ** 2 + 339 ** 2), 396 / np.sqrt(56 ** 2 + 339 ** 2)))
import json
json.dump(rows, open('calc13-5-out.json', 'w'), ensure_ascii=False)

print('\n=== 계산 13-5 (4) 이론 상자의 시연값: 영점이 틀어진 저울 ===')
true, off, noise, n = 1000.0, 200.0, 5.0, 100
print('참 무게 %.0f g, 영점 오차 +%.0f g, 읽기 오차 %.0f g. %d 번 재어 평균하면 평균의 읽기 오차 %.2f g, 그러나 평균은 %.0f g 로 +%.0f g 틀린 채로 남는다' % (true, off, noise, n, noise / np.sqrt(n), true + off, off))

print('\n=== 계산 13-5 (5) 396년이 양쪽 5%(1.96배)를 넘지 않게 하는 경계 쪽 오차의 한계 ===')
need = 396 / 1.96
print('합성 오차가 %.2f 년을 넘으면 1.96 배 이하. 점 오차 56 년을 빼면 경계 쪽 오차 %.1f 년 이상' % (need, np.sqrt(need ** 2 - 56 ** 2)))
