"""계산 10-7. (a) Wang 등(2023)의 Kerey 하위 군집 나이와 역사 서술 연대, (b) Khussainova 등(2022) 본문 추출문의 숫자 점검.
(a) 논문 값(본문 추출문): DYS448-23 하위 군집 TMRCA 289.4 ± 202.65년(ASD 방법, 세대 25년), 논문 발표 2023년. 역사 서술: 1757년 Ablai Sultan(Perdue 2005를 인용한 문장). Abilev 등(2012) 초록: 두 하위 씨족이 20~22세대 전에 갈라졌다(역사 자료).
    '±'가 표준오차인지 95% 구간인지 추출문에 없다. Wang 등의 같은 추출문 안에 Altay Kazakh 중 DYS448-23 몫이 60.6%(초록), 20.6%와 34.4%(결과)로 서로 다르게 적혀 있어 이 책은 그 몫을 쓰지 않는다.
(b) 논문 값: 1171명 = 433 + 475 + 241 + 22; AMOVA 8.91%, 19.68%, 71.40%; ΦST 0.268(표)·0.273(본문, ~tribe 모형), 0.286(표)·0.2923(본문, 주즈/부족 모형); 하플로타입 다양도 0.9938(결과)·0.9929(논의); Kozha 16명, Tore 6명, Tore의 N-M231 16.7%, Kozha의 R1a1a 31.3%, R2 6.3%, J2 18.8%.
"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
out = {}
print('(a) Wang 등(2023): Kerey 하위 군집')
t, se, yr = 289.4, 202.65, 2023
print('  TMRCA %.1f ± %.2f년 → 달력 %.0f년 (구간 %.0f~%.0f년). 세대 25년으로 %.1f세대(구간 %.1f~%.1f세대)' % (t, se, yr - t, yr - t - se, yr - t + se, t / 25, (t - se) / 25, (t + se) / 25))
ev = 1757
d = yr - ev
print('  1757년은 발표 시점에서 %d년 전. 점추정과의 차 %.1f년 = %.2f × (±%.2f)' % (d, t - d, abs(t - d) / se, se))
print('  구간 안에 든다: %s (구간이 %.0f년 폭이다)' % (('예' if t - se <= d <= t + se else '아니오'), 2 * se))
print('  Abilev 등(2012)의 하위 씨족 분기 20~22세대: 25년 세대로 %d~%d년, 30년 세대로 %d~%d년. 하위 군집 나이의 위 끝(%.1f년)은 25년 세대의 500년보다 %.1f년 젊다.' % (20 * 25, 22 * 25, 20 * 30, 22 * 30, t + se, 20 * 25 - (t + se)))
print('  → 한 하위 씨족 안의 하위 군집은 하위 씨족 분기보다 젊어야 하며 이 숫자는 그 방향과 어긋나지 않는다. 단 두 논문의 DYS448 표기와 시료가 같은지는 확인하지 못했다.')
out['wang'] = dict(calendar=yr - t, interval=[yr - t - se, yr - t + se], years_before_1757=d, z=abs(t - d) / se, gen25=t / 25)
print('\n(b) Khussainova 등(2022)')
print('  1171 = 433 + 475 + 241 + 22 = %d' % (433 + 475 + 241 + 22))
print('  Kozha 16 + Tore 6 = %d(= 22)' % (16 + 6))
print('  AMOVA 합 8.91 + 19.68 + 71.40 = %.2f' % (8.91 + 19.68 + 71.40))
print('  Tore N-M231 16.7%% = %.2f%%(1/6). Kozha R1a1a 31.3%% = %.2f%%(5/16), R2 6.3%% = %.2f%%(1/16), J2 18.8%% = %.2f%%(3/16)' % (100 / 6, 500 / 16, 100 / 16, 300 / 16))
print('  C2-M217 608/1171 = %.2f%% (논문 51.9%%)' % (608 / 1171 * 100))
print('  논문 안의 불일치: ΦST 0.268 대 0.273, 0.286 대 0.2923, 하플로타입 다양도 0.9938 대 0.9929, STRUCTURE 1163 대 1164명. 이 책은 본문 값과 표 값이 같은 모형인지 확인하지 못했다.')
print('  Tore는 6명이고 가장 흔한 하플로그룹의 이름이 추출문에 없다. 6명의 N-M231 1명(16.7%)이 확인된 전부이다.')
out['khus'] = dict(sum=433 + 475 + 241 + 22, amova_sum=8.91 + 19.68 + 71.40)
json.dump(out, open(os.path.join(HERE, 'out', 'calc-10-7.json'), 'w'), ensure_ascii=False, indent=1)
