# -*- coding: utf-8 -*-
"""계산 10-5. 울리타우 영묘 개체의 연대를 구전 인물의 연대와 맞대는 산술. 숫자는 Golden Horde 엘리트 프리프린트(bioRxiv 2025.06.11.659160)의 본문 추출문에서 옮겼다.
논문 값: Joshi 사망 1227 CE(역사 연대기); CKZ002·CKZ003·CKZ004의 방사성탄소 연대 14세기 CE, CKZ001은 '18세기까지'(as recently as the 18th century); Joshi 영묘 목재 1298~1398 CE, 관 목재 약 1245 CE;
 황금 군단(Golden Horde) 통치 1240~1480 CE; CKZ003이 CKZ001의 조상이며 둘 사이 4~5세대(100~150년); CKZ001–CKZ003 6구간 121.6 cM.
'14세기'의 경계(1301~1400 또는 1300~1399)와 보정 구간은 추출문에 없다. 이 책은 1301~1400으로 읽고 ±1년 차이를 적는다. 보정 구간 확보 필요.
"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
out = {}
J = 1227
c14 = (1301, 1400)
print('(a) CKZ002(Joshi 영묘의 남성)와 Jochi(1227 사망)')
print('  14세기(%d~%d)와의 간격: %d~%d년 (경계를 1300~1399로 읽으면 %d~%d년)' % (c14[0], c14[1], c14[0] - J, c14[1] - J, 1300 - J, 1399 - J))
print('  영묘 목재 1298~1398 CE와의 간격: %d~%d년' % (1298 - J, 1398 - J))
print('  관 목재 약 1245 CE와의 간격: %d년 (목재 연대는 나무가 베어진 해가 아니라 나이테 마지막 해일 수 있어 사용 시점은 이보다 늦을 수 있다. 이 책은 추출문에서 어느 쪽인지 확인하지 못했다)' % (1245 - J))
print('  황금 군단 통치(1240~1480) 시작은 Jochi 사망보다 %d년 뒤' % (1240 - J))
out['gap_c14'] = [c14[0] - J, c14[1] - J]; out['gap_wood'] = [1298 - J, 1398 - J]; out['gap_coffin'] = 1245 - J
print('  판단: 개체의 보정 구간이 1227을 포함하는지가 열쇠이다. 14세기로만 읽은 이 책은 포함 여부를 판정하지 못한다. 저자들도 정체를 미결로 결론짓는다.')
print('\n(b) CKZ003 → CKZ001: 4~5세대, 100~150년')
print('  암시된 세대 길이: 100/4 = %.0f년, 150/5 = %.0f년' % (100 / 4, 150 / 5))
a = (c14[0] + 100, c14[1] + 150)
print('  CKZ003이 14세기(%d~%d)이면 CKZ001은 %d~%d년 무렵이어야 한다' % (c14[0], c14[1], a[0], a[1]))
print('  CKZ001이 18세기(1701~1800)의 끝이라면 CKZ003과의 간격은 %d~%d년이고, 세대 길이 25~30년이면 %.1f~%.1f세대이다' % (1701 - c14[1], 1800 - c14[0], (1701 - c14[1]) / 30, (1800 - c14[0]) / 25))
print('  추출문의 "18세기까지"가 CKZ001 보정 구간의 젊은 끝인지 중앙인지 확인하지 못했다. 4~5세대 서술과 어긋나는지는 CKZ001의 보정 구간을 읽은 뒤에 가린다.')
out['implied_window_ckz001'] = list(a)
print('\n(c) 검증이 가능한 경계: 이 계산은 달력 산술이다. 보정(IntCal20)은 하지 않았다. 원래 논문의 표 1이 필요하다.')
json.dump(out, open(os.path.join(HERE, 'out', 'calc-10-5.json'), 'w'), ensure_ascii=False, indent=1)
