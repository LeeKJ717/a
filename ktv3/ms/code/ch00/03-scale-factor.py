"""계산 0-3: 이 장 지도의 투영에서 거리 척도의 어긋남. 각 지도의 네 모서리와 중앙에서 동서 방향과 남북 방향으로 100 km(측지선) 가는 두 점을
투영해 투영 위 거리 / 100 km 를 구한다. 1 이면 거리가 맞는 곳이다."""
import os, sys
from pyproj import Geod, Transformer
G = Geod(ellps='WGS84')
AEA = '+proj=aea +lat_1=%g +lat_2=%g +lat_0=%g +lon_0=%g +datum=WGS84 +units=m +no_defs'
MAPS = {'유라시아 개관': (AEA % (38, 68, 52, 82), (10, 20, 170, 82), [(30, 40), (82, 40), (130, 40), (82, 52), (82, 70), (130, 55), (45, 55)]),
        '몽골 고원': (AEA % (42, 55, 48, 105), (90, 41, 121, 54), [(92, 42), (105, 48), (118, 42), (92, 53), (118, 53)]),
        '알타이와 시베리아': (AEA % (50, 66, 58, 94), (66, 48, 118, 68), [(70, 50), (94, 58), (115, 50), (70, 66), (115, 66)]),
        '중앙아시아': (AEA % (37, 49, 43, 68), (54, 36, 90, 49), [(56, 38), (68, 43), (88, 38), (56, 48), (88, 48)]),
        '카스피해와 흑해': (AEA % (40, 54, 47, 44), (28, 39, 58, 53), [(30, 41), (44, 46), (56, 41), (30, 51), (56, 51)])}
print('지도 | 지점(경도, 위도) | 동서 100 km 의 투영 길이 비 | 남북 100 km 의 투영 길이 비')
for nm, (crs, bb, pts) in MAPS.items():
    t = Transformer.from_crs(4326, crs, always_xy=True)
    for lo, la in pts:
        lo2, la2, _ = G.fwd(lo, la, 90, 100000)
        lo3, la3, _ = G.fwd(lo, la, 0, 100000)
        x0, y0 = t.transform(lo, la); x1, y1 = t.transform(lo2, la2); x2, y2 = t.transform(lo3, la3)
        e = ((x1 - x0) ** 2 + (y1 - y0) ** 2) ** 0.5 / 1e5; n = ((x2 - x0) ** 2 + (y2 - y0) ** 2) ** 0.5 / 1e5
        print('%s | (%g E, %g N) | %.4f | %.4f' % (nm, lo, la, e, n))
