"""계산 7-7. 논문 본문(또는 요약)에 적힌 개수와 비율의 산술 점검. 입력은 모두 읽은 쪽에 적힌 숫자이며, 요약 도구를 거쳤으므로 옮김 오류일 가능성이 있다."""
from fractions import Fraction
def show(name, ok, detail): print('%-58s %-6s %s' % (name, '맞음' if ok else '어긋남', detail))
# Liu 2017: 새 보리 낟알 70개 = 중국 54 + 인도 12 + 키르기스스탄 1 + 파키스탄 3
s = 54 + 12 + 1 + 3; show('Liu 2017 보리 낟알 70 = 54+12+1+3', s == 70, '합 %d' % s)
# Long 2018 (Wagner 등 2018 보고서): 베이즈 모형 자료 73 = 35+11+6+7+14
s = 35 + 11 + 6 + 7 + 14; show('Long 2018 모형 자료 73 = 35+11+6+7+14', s == 73, '합 %d' % s)
# Hunt 2008: 기장속 41곳, 강아지풀속 33곳, 둘 다 9곳, 전체 60곳
u = 41 + 33 - 9; show('Hunt 2008 41+33-9 = 60?', u == 60, '41+33-9 = %d (60이 맞으려면 둘 다 인 곳이 %d곳)' % (u, 41 + 33 - 60))
# Spengler 등 2014 Tasbas: 기장 출현율 50%(전체 청동기 16개 시료), 72.7%(2a 단계 11개 시료)
for num, den, tgt, lab in ((8, 16, 50.0, '전체 청동기 시료 16'), (8, 11, 72.7, '2a 단계 시료 11')):
    v = 100 * num / den; show('Tasbas 기장 출현율 %s%% = %d/%d (%s)' % (tgt, num, den, lab), abs(v - tgt) < 0.05, '%.2f%%' % v)
# 밀 출현율 57.1%를 분모 31 이하의 분수로 쓰면
cand = [(n, d) for d in range(1, 32) for n in range(1, d + 1) if abs(100 * n / d - 57.1) < 0.05]
print('밀 57.1%를 분모 31 이하의 분수로 쓰면:', cand[:8], '| 분모 11 또는 16인 것:', [c for c in cand if c[1] in (11, 16)])
# 밀도: 기장 53알 / 0.75 알/L = 처리한 흙(L)
v = 53 / 0.75; print('기장 53알 ÷ 0.75알/L = %.1f L (전체 처리량 약 106 L의 %.0f%%)' % (v, 100 * v / 106))
# 보리 낟알 본문 446 대 표 577, 밀 8 대 3, 완두 59 대 80
print('Tasbas 본문과 표의 개수 차: 보리 %d, 밀 %d, 완두 %d (요약기가 본문과 표가 다르다고 알림; 원문 확인 필요)' % (577 - 446, 8 - 3, 80 - 59))
# Stevens 2016: 중국 밀·보리 113곳 중 14곳이 기원전 3000~2200
print('Stevens 2016: 113곳 중 14곳 = %.1f%%' % (100 * 14 / 113))
# Dodson 2013: 35개 연대 / 18개 유적
print('Dodson 2013: 35개 / 18곳 = %.2f개/곳' % (35 / 18))
# Motuzaite 2022: 78 + 84
print('Motuzaite 2022: 78 + 84 = %d 시료, 17곳, 방사성탄소 13개 시료/6곳' % (78 + 84))
# Heron 2016: Majeon-ri 15 토기 조각 중 7에서 miliacin
print('Heron 2016: Majeon-ri 7/15 = %.1f%%' % (100 * 7 / 15))
# Zhao? Frachetti 2007: 34개 연대 중 단계별 수
print('Begash 단계별 수: 1a 4, 1b 4, 2 3, 3a 3, 3b 9, 4 6, 5 2, 6 3 합 =', 4 + 4 + 3 + 3 + 9 + 6 + 2 + 3)
# Zhaogezhuang: 표 구간 895~791(104년 폭), 본문 895~751(144년 폭)
print('Zhaogezhuang 표 구간 폭 %d년, 본문 구간 폭 %d년, 차 %d년' % (895 - 791, 895 - 751, (895 - 751) - (895 - 791)))
# Motuzaite 2022 같은 시료의 두 연대: 결과 2287~2092, 논의 2460~2204
print('Motuzaite 2022 BTC-KY-F45: 결과 2287~2092 BC(폭 %d), 논의 2460~2204 BC(폭 %d), 시작 차 %d년, 끝 차 %d년' % (2287 - 2092, 2460 - 2204, 2460 - 2287, 2204 - 2092))
