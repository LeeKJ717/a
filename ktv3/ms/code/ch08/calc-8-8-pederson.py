# -*- coding: utf-8 -*-
"""계산 8-8. Pederson 등(2014) 본문 추출문의 숫자로 하는 산술. 논문의 값과 이 책의 산술을 구분한다.
논문 값(본문 추출문): 복원 900~2011 CE, 시료 107그루(시베리아 소나무, Khorgo 용암 지대), 목표 6~9월 scPDSI(자기보정 Palmer 가뭄 지수), 보정 1959~2009, 설명 분산 55.8%,
 1211~1225 CE '몽골 다우기' 평균 scPDSI 0.600 ± 0.589, 장기 평균 −0.546 ± 1.550(900~2009 CE로 읽음), 극아시아 기온 이상 1211~1225 −0.118 ± 0.147 °C 대 장기 −0.311 ± 0.292 °C,
 2000~2009 기온 복원 평균 0.74 °C 대 장기 −0.31 °C(SD 0.29), 1226 CE에 4년 가뭄 시작.
'±'가 표준편차인지 표준오차인지 추출문에 없다. 이 책은 아래에서 두 읽기를 모두 적는다.
"""
import os, json, math
HERE = os.path.dirname(os.path.abspath(__file__))
out = {}
print('(a) 구간 길이: 900~2011 CE = %d년(양 끝 포함), 1211~1225 = %d년, 1226부터 4년 가뭄 = 1226~%d' % (2011 - 900 + 1, 1225 - 1211 + 1, 1226 + 3))
R2 = 0.558; r = math.sqrt(R2)
print('(b) 설명 분산 %.1f%% → 상관계수 r = sqrt(%.3f) = %.3f(부호 제외). 보정 기간 1959~2009 = %d년' % (R2 * 100, R2, r, 2009 - 1959 + 1))
out['r_from_R2'] = r
pl, plsd, lt, ltsd = 0.600, 0.589, -0.546, 1.550
diff = pl - lt
print('(c) 다우기 평균과 장기 평균의 차 = %.3f scPDSI 단위. 장기 ±1.550을 연 값의 표준편차로 읽으면 %.2f 표준편차 위이다.' % (diff, diff / ltsd))
se15 = ltsd / math.sqrt(15)
print('    15년 평균의 표준오차를 연 값이 서로 독립이라고 가정해 1.550/sqrt(15) = %.3f 로 두면 z = %.2f (시연값: 연 값은 자기상관이 있어 실제 z는 이보다 작다. 이 책은 논문의 자기상관 값을 읽지 못했다)' % (se15, diff / se15))
print('    다우기의 ±0.589를 15년 안의 연 값 표준편차로 읽으면 평균의 표준오차는 %.3f' % (plsd / math.sqrt(15)))
out['pluvial_minus_longterm'] = diff; out['z_if_sd'] = diff / ltsd; out['z_independent_demo'] = diff / se15
dT = (-0.118) - (-0.311)
print('(d) 극아시아 기온: 1211~1225 − 장기 = %.3f °C. 장기 ±0.292를 표준편차로 읽으면 %.2f 표준편차(논문은 "특별히 뜨겁지는 않다"고 적음)' % (dT, dT / 0.292))
dT2 = 0.74 - (-0.31); z2 = dT2 / 0.29
print('    2000년대 복원 기온 0.74 − (−0.31) = %.2f °C = %.2f 표준편차(논문의 ">3.5 SD"와 같은 방향)' % (dT2, z2))
out['temp_pluvial_z'] = dT / 0.292; out['temp_2000s_z'] = z2
print('(e) 같은 논문 안의 순위 서술 두 가지: Fig. 4 설명은 2000년대 가뭄이 1,112년 중 세 번째로 심하다(1120년대, 1180년대 다음)고 하고, 논의는 1180년대 가뭄과 "맞먹는다"고 한다. 추출문에서 두 서술이 어떻게 맞춰지는지 확인하지 못했다.')
print('(f) 제1권 5장과의 대조: 제1권은 이 논문을 Park 등(2017)을 거쳐 "13세기 여름 강수 증가"로 옮겼다. 본문 추출문의 복원 목표는 6~9월 scPDSI이며 강수와의 상관은 r = 0.49, 기온과는 r = −0.54이다.')
print('    scPDSI 0.600은 강수 증가량이 아니라 습윤 지수의 값이다. 강수(mm)의 증가는 이 논문에서 읽은 숫자가 아니다.')
json.dump(out, open(os.path.join(HERE, 'calc-8-8-pederson.json'), 'w'), ensure_ascii=False, indent=1)
