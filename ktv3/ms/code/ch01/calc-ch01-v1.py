edges = np.arange(2.0, 12.0, 1.0)
def table(group, title):
    print('\n[%s] 칸: 아래 경계~위 경계 ka. 값은 그 칸을 덮는 기록 중 +1 비율 - -1 비율의 평균(-1~+1), 괄호 안은 덮는 기록 수' % title)
    for lo in edges[::-1]:
        hi = lo + 1.0
        vals = []
        for nm, iv in group.items():
            v = [s for (a, b, s) in iv if overlap((a, b), (lo, hi)) >= 0.5]   # 칸의 절반 이상을 덮을 때만 센다
            if v:
                vals.append(np.mean(v))
        if vals:
            print('  %4.0f~%4.0f ka : %+.2f  (n=%d)' % (lo, hi, np.mean(vals), len(vals)))
        else:
            print('  %4.0f~%4.0f ka : -  (n=0)' % (lo, hi))
table(REC, '몬순 가장자리 13개')
table(WEST, '참고: 편서풍 쪽 2개(사이람, 헥시). 개수가 적어 비교의 근거로 쓰지 않는다')
def longest_wet(iv):
    best = None
    for a, b, s in iv:
        if s > 0 and (best is None or abs(a - b) > abs(best[0] - best[1])):
            best = (a, b)
    return best
