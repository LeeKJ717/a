def overlap(a, b):
    """두 구간 (시작, 끝)의 겹친 길이. 단위는 입력과 같다. 구간은 큰 수가 앞서도 된다."""
    a0, a1 = sorted(a); b0, b1 = sorted(b)
    return max(0.0, min(a1, b1) - max(a0, b0))

