# -*- coding: utf-8 -*-
"""계산 3-7: 중앙 야쿠티아 열카르스트 호수 퇴적물의 퇴적 속도(Ulrich 등 2019, 2021의 숫자).
깊이는 표면 아래 cm, 연대는 논문이 적은 보정 연대(cal BP). 논문이 적은 연대 오차를 정규분포로 보고 몬테카를로(10만 번)로 속도 구간을 낸다.
퇴적 속도 = 깊이 차 / 연대 차. 두 점 사이가 한 장의 연속 퇴적이라고 가정한 평균이며 틈(퇴적 중단)이 있으면 평균이 낮아진다.
"""
import numpy as np
rng = np.random.default_rng(3107)
def rate(d1, a1, s1, d2, a2, s2, n=100000):
    dz = abs(d2 - d1)
    dt = (a1 + rng.normal(0, s1, n)) - (a2 + rng.normal(0, s2, n))   # a1 이 오래된 쪽
    ok = dt > 0
    r = dz / dt[ok] * 10      # mm/년
    return dz, a1 - a2, ok.mean(), np.percentile(r, [2.5, 50, 97.5])
print('=== 계산 3-7 (1) Ulrich 등(2019): 코어별 연속 점 사이 ===')
cases = [
    ('KB7 (거의 연속 5개 중 첫째와 마지막, 320~60 cm)', 320, 6582, 78, 60, 5752, 102),
    ('KB1 (3개 중 첫째와 마지막, 243~125 cm)', 243, 3314, 62, 125, 1812.5, 72.5),
    ('YU3 (185~170 cm 의 34865 와 40~36 cm 의 3975: 사이 틈이 있는 쌍)', 170, 34865, 235, 40, 3975, 102),
]
OUT = {}
for name, d1, a1, s1, d2, a2, s2 in cases:
    dz, dt, okf, pr = rate(d1, a1, s1, d2, a2, s2)
    OUT[name.split(' ')[0]] = [float(x) for x in pr]
    print('%-70s Δ깊이 %5.0f cm Δ연대 %6.0f 년 | 속도 mm/년 2.5%%=%.3f 50%%=%.3f 97.5%%=%.3f' % (name, dz, dt, pr[0], pr[1], pr[2]))
print('주: KB7 의 5개 점 중 가운데 점들은 이 책이 얻지 못했다. 양 끝 두 점으로만 평균을 낸다.')
print()
print('=== 계산 3-7 (2) Ulrich 등(2021): 알라스 호수 코어 YU-L7 ===')
pts = [(520, 3740, 70), (748, 13750, 340)]
for (d1, a1, s1), (d2, a2, s2) in zip(pts[1:], pts[:-1]):
    dz, dt, okf, pr = rate(d1, a1, s1, d2, a2, s2)
    OUT['YU-L7'] = [float(x) for x in pr]
    print('깊이 %d→%d cm, 연대 %d→%d cal BP: Δ깊이 %d cm, Δ연대 %d 년, 속도 %.3f mm/년 (95%%: %.3f~%.3f)' % (d1, d2, a1, a2, dz, dt, pr[1], pr[0], pr[2]))
print('같은 코어의 표면(0 cm)에서 520 cm(3740 cal BP)까지 평균 = 520 cm / 3740 년 = %.3f mm/년 (표면 연대 0 가정)' % (520 / 3740 * 10))
print('같은 코어의 748~1278 cm 사이 ... 논문 표의 1278 cm 는 > 24570 14C BP(하한)이라 속도를 낼 수 없다')
print()
print('=== 계산 3-7 (3) 속도 비교 ===')
print('중앙값 비: KB7 3.137 / KB1 0.786 = %.1f ; KB7 / YU3(틈 포함) 0.042 = %.0f ; KB7 / YU-L7 0.228 = %.1f (서로 다른 분지와 구간의 평균이라 한 분지의 시간 변화로 읽지 않는다)' % (3.137/0.786, 3.137/0.042, 3.137/0.228))
print('Ulrich 등(2019) 4단계 길이: 11~9 ka(%d년), 7~5 ka(%d년), 3.5~1.5 ka(%d년), 1.5 ka 이후(%d년)' % (2000, 2000, 2000, 1500))
print('7~5 ka 단계를 KB7 6582~5752 cal BP 가 덮는다: 겹침 = %d 년(%.0f%%)' % (min(7000, 6582) - max(5000, 5752), (min(7000, 6582) - max(5000, 5752)) / 2000 * 100))

import json
json.dump(OUT, open('calc3-7-out.json', 'w'))
