"""계산 3-6: Büntgen 등(2016, Nature Geoscience)의 알타이 나이테 숫자와 Solomina 등(2016)의 알타이 전진 묶음을 되풀이한다.
(1) 660계열, 234,399 개 나이테 폭에서 평균 계열 길이를 구해 논문의 '평균 나무 나이 355년'과 견준다.
(2) '가장 서늘한 20개 알타이 10년 가운데 13개가 6~7세기'를 우연으로 볼 확률(초기하분포; 두 세기 = 20개 10년 / 전체 약 200개 10년이라는 가정은 이 책의 것).
(3) Solomina 등(2016)이 적은 알타이 나무 손상 전진 연대 묶음 20개의 비율.
"""
import numpy as np
from scipy.stats import hypergeom, binom
print('=== 계산 3-6 (1) 계열 수와 평균 길이 ===')
live, relict = 152, 508
print('살아 있는 %d + 유물 %d = %d 계열 (논문 660)' % (live, relict, live + relict))
rings = 234399
print('%d / %d = %.1f 년 (논문: 평균 나무 나이 355년)' % (rings, live + relict, rings / (live + relict)))
print('평균 성장률 0.44 mm/년 이면 한 계열 평균 길이 = 355 × 0.44 = %.0f mm = %.1f cm 반지름 성장' % (355 * 0.44, 355 * 0.44 / 10))
print('전체 나이테 폭 합 = %d × 0.44 mm = %.1f m' % (rings, rings * 0.44 / 1000))
print('복제 수 최대 240(1279 AD), 최소 10(98 AD): 계열이 1279년에 가장 많이 겹친다. 계열당 355년이라면 한 해를 덮는 계열 수 평균 = %d × 355 / 2370 년 = %.0f (연대 범위 359 BC~2011 AD 를 2370년으로 본 대략값)' % (660, 660 * 355 / 2370))
print()
print('=== 계산 3-6 (2) 가장 서늘한 10년의 시기 편중 ===')
print('논문: 가장 서늘한 알타이 10년 20개 중 13개가 6~7세기; 중앙아시아 가장 서늘한 여름 20개 중 13개가 536 AD 이후 6세기')
for Ndec in (200, 230, 236):
    # 6~7세기 = 20개 10년
    K = 20
    p_ge13 = hypergeom.sf(12, Ndec, K, 20)
    print('  전체 10년 %d 개 중 6~7세기 %d 개, 20개를 임의로 뽑을 때 13개 이상이 들 확률 = %.2e' % (Ndec, K, p_ge13))
for Nyr in (2000, 2370):
    K = 100   # 536 이후 6세기 = 약 64년(536~599); 아래는 6세기 전체 100년을 쓴 느슨한 상한
    print('  여름 단위: 전체 %d 년 중 6세기 100년, 20개 중 13개 이상 확률(느슨한 상한) = %.2e' % (Nyr, hypergeom.sf(12, Nyr, K, 20)))
    K2 = 64
    print('     6세기 중 536 AD 이후 64년(536~599)만 세면 = %.2e' % hypergeom.sf(12, Nyr, K2, 20))
print('주: 이 확률은 순서 없는 임의 추출을 가정하며, 서늘한 해는 실제로는 화산 폭발 뒤에 이어서 나타나는 자기상관이 있어 확률이 이보다 훨씬 크다. 논문의 방법이 아닌 이 책의 점검이다.')
print()
print('=== 계산 3-6 (3) Solomina 등(2016): 알타이 나무 손상 전진 묶음 ===')
cl = {'1200~1260': 3, '1320~1380': 4, '1440~1510': 5, '1640~1740': 8}
tot = sum(cl.values())
print('묶음 4개의 연대 개수 합 = %d' % tot)
for k, v in cl.items():
    print('  CE %s: %d개 (%.0f%%)' % (k, v, v / tot * 100))
span = {'1200~1260': 60, '1320~1380': 60, '1440~1510': 70, '1640~1740': 100}
print('묶음 길이 합 = %d 년. 1200~1750 사이(550년)에서 묶음이 차지하는 비율 = %.0f%%' % (sum(span.values()), sum(span.values()) / 550 * 100))
print('묶음 밀도(개/10년): ', {k: round(v / span[k] * 10, 2) for k, v in cl.items()})
print('주: 개수는 나이를 낸 나무 수이므로 시료 채취가 많은 골짜기, 해에 따라 늘 수 있다. 빙하 규모가 아니다.')
