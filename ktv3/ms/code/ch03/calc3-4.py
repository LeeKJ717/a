# -*- coding: utf-8 -*-
"""계산 3-4: Walter Anthony 등(2014, Nature 511) 열카르스트 호수 탄소 숫자의 내적 일관성과 오차 전파.
입력(논문 초록과 본문): 홀로세 탄소 159 ± 24 Pg(베링지아 알라스 0.93 백만 km²), yedoma 방출 100 ± 34 Pg, 비율 약 1.6,
20개 시베리아 호수 퇴적물의 홀로세 탄소 집적 47 ± 10 g C m^-2 yr^-1 (평균 ± 표준오차), 이끼 우세 8개 호수 89 ± 15,
호수 시작 약 14~9 kyr 전, 순 기후 효과 전환 약 5 kyr 전, 순 강제력 -0.06 ± 0.02 W m^-2.
오차는 서로 독립인 정규분포로 가정한다(이 책의 가정이며 논문의 오차 처리가 아니다).
"""
import numpy as np
rng = np.random.default_rng(3104)
N = 400000
print('=== 계산 3-4 (1) 비율 159/100 ===')
print('중앙값끼리: %.3f (논문: 약 1.6배)' % (159 / 100))
c = rng.normal(159, 24, N); y = rng.normal(100, 34, N)
ok = y > 0
r = c[ok] / y[ok]
print('몬테카를로 (y>0 만, %.4f 제외): 비율 중앙 %.2f, 2.5%%=%.2f, 97.5%%=%.2f' % (1 - ok.mean(), np.median(r), *np.percentile(r, [2.5, 97.5])))
print('  → 비율의 95%% 구간은 1 을 포함하는가: %s ; 비율 < 1 확률 %.3f' % ('예' if np.percentile(r, 2.5) < 1 else '아니오', (r < 1).mean()))
print('  (yedoma 100 ± 34 의 오차가 크고 비율이 분모에 들어가 구간이 위로 길게 늘어난다)')
print()
print('=== 계산 3-4 (2) 면적 평균 탄소량과 호수 퇴적물 집적률의 관계 ===')
area = 0.93e12         # m²  (0.93 백만 km²)
per = 159e15 / area    # g C / m²  (1 Pg = 1e15 g)
print('159 Pg / 0.93 백만 km² = %.0f g C m^-2 = %.0f kg C m^-2' % (per, per / 1000))
for rate in (47, 89):
    yrs = per / rate
    print('  집적률 %d g C m^-2 yr^-1 로 채웠다면 걸리는 시간 = %.0f 년 (%.1f kyr)' % (rate, yrs, yrs / 1000))
print('  호수 시작 약 14~9 kyr 전에서 지금까지 %d~%d 년 동안 계속 쌓였다면 최대 면적 평균 = %.0f~%.0f kg C m^-2 (집적률 47 일 때)' % (9000, 14000, 47 * 9000 / 1000, 47 * 14000 / 1000))
print('  → 면적 평균(약 %.0f kg/m²)이 호수 바닥의 연속 집적(수백 kg/m²)보다 훨씬 작은 이유는 이 책이 논문 본문 전체를 읽지 못해 확인하지 못했다.' % (per / 1000))
print('    가능한 설명(검증 아님): 알라스 바닥의 퇴적이 깊은 호수에서만 빠르고 면적 평균에는 얕은 바닥, 배수된 분지가 섞임')
print()
print('=== 계산 3-4 (3) 집적률 평균의 표준오차와 표본 수 ===')
se, n = 10, 20
print('표준오차 10, n = 20 이면 표준편차 = %.1f g C m^-2 yr^-1 (표준편차/평균 = %.2f)' % (se * np.sqrt(n), se * np.sqrt(n) / 47))
se2, n2 = 15, 8
print('이끼 우세 n = 8, 표준오차 15 이면 표준편차 = %.1f (표준편차/평균 = %.2f)' % (se2 * np.sqrt(n2), se2 * np.sqrt(n2) / 89))
d = 89 - 47; sd = np.hypot(15, 10)
print('두 평균의 차 %d, 표준오차 합성 = %.1f, z = %.2f (독립 가정; 이끼 8개가 20개에 들어 있으면 독립이 아니다)' % (d, sd, d / sd))
print()
print('=== 계산 3-4 (4) 강제력 ===')
print('최대 온난화 효과 +0.06 ± 0.03 W m^-2 와 현재 -0.06 ± 0.02: 두 값의 차 = %.2f ± %.3f (독립 가정)' % (0.06 - (-0.06), np.hypot(0.03, 0.02)))
