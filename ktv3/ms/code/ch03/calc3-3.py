"""계산 3-3: 시베리아 남동부 빙하 면적 변화율을 논문 숫자로 되풀이한다.
자료: Osipov & Osipova(2014, Annals of Glaciology 55(66)), Osipov & Osipova(2018, Geosciences 8(5):148), 얼음과 눈 2015년 5월호의 초록(저자 확인 못함), Nazarov 등(2022).
논문이 적은 비율과 연율을 같은 두 점에서 다시 나눠 맞는지 본다.
"""
import numpy as np
print('=== 계산 3-3 (1) 피크 토포그라포프(동사얀) 빙하 7개, Osipov & Osipova 2018 ===')
a0, a1 = 8.1, 3.8
loss = (a0 - a1) / a0 * 100
print('면적 %.1f → %.1f km²: 감소 %.1f%% (논문 53%%)' % (a0, a1, loss))
for y0 in (1850, 1860):
    for y1 in (2010,):
        print('  소빙기 윤곽 연도 %d → %d (%d년): 연 %.3f%% (논문 0.33%%/년)' % (y0, y1, y1 - y0, loss / (y1 - y0)))
print()
print('=== 계산 3-3 (2) 동남 시베리아 세 산맥, 소빙기 이후 약 160년 ===')
print('얼음과 눈 초록: 평균 59%% 감소, 연 0.37%% → 59/160 = %.3f%%/년 ; 59/0.37 = %.0f 년' % (59 / 160, 59 / 0.37))
print('Osipov & Osipova 2014: 소빙기(1850) → 2006/11 (%d~%d년) 무빙하파편 면적 59%% 감소' % (2006 - 1850, 2011 - 1850))
for yrs in (156, 161):
    print('   %d년이면 연 %.3f%%' % (yrs, 59 / yrs))
print('말단 후퇴: 평균 550 m, 연 3.5 m → 550/3.5 = %.0f 년 ; 160년이면 연 %.2f m' % (550 / 3.5, 550 / 160))
print()
print('=== 계산 3-3 (3) 코다르(Kodar) ===')
print('논문: 소빙기→2006/11 62%% 감소, 연 0.39%% → 62/%.0f = %.3f ; 62/0.39 = %.0f 년' % (160, 62 / 160, 62 / 0.39))
print('논문: 1953/63→2001/02 23%% 감소, 연 0.55%% → 23/0.55 = %.1f 년. 가능한 간격: ' % (23 / 0.55), end='')
for a, b in ((1953, 2001), (1953, 2002), (1963, 2001), (1963, 2002), (1958, 2001.5)):
    print('%s~%s=%.1f년(연 %.2f%%)' % (a, b, b - a, 23 / (b - a)), end='; ')
print()
print('면적 목록: Plastinin(1998) 재인용 39빙하 15.25 km²(그 가운데 노출 얼음 11.25 km², 조사 연도는 확인 필요) → 2001/02년 42빙하 11.68 km²')
print('   감소 %.1f%% (빙하 수와 면적 정의가 다른 두 집합이다. 논문 23%%와 같은 비교인지는 이 책이 확인하지 못했다)' % ((15.25 - 11.68) / 15.25 * 100))
print('2001/02년 42빙하 11.68 km² → 2009년 36빙하 9.12 km² (6개 소멸): 감소 %.1f%% ; 사라진 6개를 빼고 다시 지도화한 36개의 2001/02 면적은 이 논문 초록에서 알 수 없다' % ((11.68 - 9.12) / 11.68 * 100))
print('소빙기 61빙하 31.65 km² → 현재 51빙하 약 15 km²: 감소 %.1f%% (논문의 무빙하파편 면적 59%%와 다름: 얼음 덮개 포함 여부, 연대가 다름)' % ((31.65 - 15) / 31.65 * 100))
print('비교용: 코다르 9.12/11.68 = %.3f' % (9.12 / 11.68))
print()
print('=== 계산 3-3 (4) 지의류 크기와 나이, 코다르(25.7 mm)와 알타이 아크투 단계(20~41 mm) ===')
print('Osipov & Osipova 2014: 코다르 모레인의 Rhizocarpon 평균 25.7 mm, 알타이 성장 곡선으로 모레인 나이 1680~1820년.')
for age_year in (1680, 1820):
    for obs in (2009,):
        yrs = obs - age_year
        print('  나이 %d년(조사 %d 가정): 평균 선형 성장 = %.1f/%d = %.3f mm/년' % (age_year, obs, 25.7, yrs, 25.7 / yrs))
print('Nazarov 등 2022: 볼샤야 아크투 지의류 기준 안정화 약 1830 AD, 추정 나이 약 182년; 마셰이 약 263년. 아크투 단계 지의류 20~41 mm.')
for yrs, tag in ((182, '볼샤야 아크투'), (263, '마셰이')):
    print('  %s: 나이 %d년이면 20~41 mm 은 평균 %.3f~%.3f mm/년 (성장은 처음 몇십 년 정착 지연, 이후 곡선이라 선형 평균은 대략값)' % (tag, yrs, 20 / yrs, 41 / yrs))
print('주의: 위 mm/년은 이 책의 나눗셈이고 논문의 성장 곡선이 아니다.')
