"""계산 3-8: 3장 이론 상자에 쓰는 시연값. 논문 숫자가 아니라 이 책이 정한 가상 값이다."""
import math
from math import comb
print('=== 계산 3-8 (1) 방사성탄소 관례식 t = -8033 ln F (시연값) ===')
for F in (0.80, 0.50, 0.45, 0.10):
    print('  F = %.2f -> t = %.0f BP' % (F, -8033 * math.log(F)))
print()
print('=== 계산 3-8 (2) Nye 모형 t(z) = -(H/a) ln(1 - z/H) (시연값: H = 100 m w.e., a = 0.30 m w.e./년) ===')
H, a = 100.0, 0.30
for z in (10, 30, 50, 80, 95):
    t = -(H / a) * math.log(1 - z / H)
    print('  깊이 %2d m -> %7.1f 년 ; 두께 변화 없는 단순 나눗셈 z/a = %6.1f 년' % (z, t, z / a))
print('  층 두께는 표면에서 a, 깊이 z 에서 a(1 - z/H): z = 50 이면 %.3f, z = 95 이면 %.3f m w.e./년' % (a * 0.5, a * 0.05))
print()
print('=== 계산 3-8 (3) 초기하 분포 (시연값: 10개 가운데 3개에 표시, 3개를 임의로 뽑음) ===')
N, K, n = 10, 3, 3
for k in range(0, 4):
    print('  표시된 것이 정확히 %d 개 뽑힐 확률 = %d/%d = %.4f' % (k, comb(K, k) * comb(N - K, n - k), comb(N, n), comb(K, k) * comb(N - K, n - k) / comb(N, n)))
print()
print('=== 계산 3-8 (4) 퍼센트 감소를 연율로 바꾸는 두 방법 (시연값: 100년 동안 50% 감소) ===')
print('  처음 면적 대비 직선 연율 = %.3f %%/년 ; 복리 연율 = %.3f %%/년' % (50 / 100, (1 - 0.5 ** (1 / 100)) * 100))
print('  논문 값(Osipov & Osipova 2018)은 첫째 방식으로 되풀이됨: 53.1/160 = %.3f' % (53.1 / 160))
