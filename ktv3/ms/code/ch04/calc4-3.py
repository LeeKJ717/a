# -*- coding: utf-8 -*-
"""계산 4-3: 쿨룬다(Kulunda, 서시베리아 남부) 빅 야로보예 호수 코어의 연대 모형과 꽃가루 구역(Rudaya 등 2012, 표 1과 본문).
연대는 호수 비와(Biwa) 호 지자기 편각 극값 대비로 옮긴 4점(표 1)과 이 책이 계산한 구간별 속도이다.
(1) 구간별 퇴적 속도, (2) 코어 바닥(404 cm)까지 외삽, (3) 꽃가루 구역 길이의 합, (4) 시료 간격과 시간 해상도.
"""
import numpy as np
print('=== 계산 4-3 (1) 표 1: 대비한 4점 사이의 퇴적 속도 ===')
d = np.array([0.18, 1.76, 2.56, 3.46])       # m
a = np.array([0.52, 2.31, 3.05, 4.03])       # ka (비와 호 연대)
for i in range(3):
    print('  %.2f→%.2f m: %.2f ka → %.2f ka: %.3f m/ka = %.3f mm/년 (%.0f 년/cm)' % (d[i], d[i + 1], a[i], a[i + 1], (d[i + 1] - d[i]) / (a[i + 1] - a[i]), (d[i + 1] - d[i]) / (a[i + 1] - a[i]), (a[i + 1] - a[i]) * 1000 / ((d[i + 1] - d[i]) * 100)))
r_all = (d[-1] - d[0]) / (a[-1] - a[0])
print('  네 점 전체 평균: %.3f m/ka' % r_all)
print('  첫 점에서 표면까지(0.18 m, 0.52 ka 연대): %.3f m/ka' % (0.18 / 0.52))
print()
print('=== 계산 4-3 (2) 코어 바닥(404 cm)까지 외삽 ===')
r_last = (d[3] - d[2]) / (a[3] - a[2])
a_bot = a[3] + (4.04 - d[3]) / r_last
print('  마지막 구간 속도 %.3f m/ka 로 3.46 m → 4.04 m(0.58 m) 외삽: 바닥 연대 %.2f ka (논문: 코어는 약 4.4 ka 를 덮음)' % (r_last, a_bot))
r_avg = r_all
a_bot2 = a[3] + (4.04 - d[3]) / r_avg
print('  전체 평균 속도 %.3f m/ka 로 외삽: %.2f ka' % (r_avg, a_bot2))
need = (4.04 - d[3]) / (4.4 - a[3])
print('  바닥이 4.4 ka 가 되려면 마지막 4점 아래 구간 속도가 %.3f m/ka 여야 한다(위 구간 속도와 비교해 %.0f%% 높음)' % (need, (need / r_last - 1) * 100))
print('  → 논문 본문의 "4.4 ka"와 표 1 의 단순 외삽이 약 %.2f ka 어긋난다. 어떤 대비점을 더 썼는지 이 책은 확인하지 못했다.' % (a_bot - 4.4))
print()
print('=== 계산 4-3 (3) 꽃가루 구역 길이의 합 ===')
Z = [('PZ I', 4.4, 3.75), ('PZ II', 3.75, 2.66), ('PZ III', 2.66, 1.37), ('PZ IV', 1.37, 0.09), ('PZ V', 0.09, 0.0)]
tot = 0
for n, a0, a1 in Z:
    print('  %-6s %.2f→%.2f ka: %.0f 년' % (n, a0, a1, (a0 - a1) * 1000)); tot += (a0 - a1) * 1000
print('  합 = %.0f 년 (4.4 ka 에서 현재까지). PZ V 는 AD 1860 이후이고 0.09 ka = 90 년 전 = 1950 - 90 = AD %d 이다' % (tot, 1950 - 90))
print()
print('=== 계산 4-3 (4) 시료 간격과 시간 해상도 ===')
print('꽃가루 23개 시료, 코어 404 cm, 평균 계수 317 입자: 시료 간격 평균 %.1f cm (22개 간격 기준; 시료 위치는 논문에서 읽지 못함)' % (404 / 22))
print('  평균 속도 %.3f m/ka 로 환산하면 한 시료 간격은 약 %.0f 년' % (r_all, 404 / 22 / 100 / r_all * 1000))
print('  4.4 ka / 22 간격 = %.0f 년/간격 (논문 연대 기준)' % (4400 / 22))
print('  계수 317 입자에서 비율 p 의 표준오차(이항 근사): p=0.5 일 때 %.3f, p=0.1 일 때 %.3f' % (np.sqrt(.25 / 317), np.sqrt(.09 / 317)))
