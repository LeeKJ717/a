# -*- coding: utf-8 -*-
"""계산 4-6: 꽃가루로 복원한 강수량의 신호 대 잡음(Tian 등 2014, 바얀 누르 호수, 몽골 서북부).
논문 숫자: 현대 표면 시료 90개(강수 65~328 mm), WA-PLS 2성분 전달함수 r2(jack)=0.58, RMSEP=41 mm, 최대 편향 98 mm,
복원 강수량 85~223 mm(늦은 빙기~홀로세), 시료별 오차 41.7~51.7 mm(평균 늦은 빙기~이른 홀로세 약 46 mm, 중~늦은 홀로세 약 43 mm),
시료 75개, 시료 간격 평균 약 210년, 퇴적 속도 10년/cm, 표면 연대 -45 cal BP.
이 책의 점검: 시료별 오차를 정규분포(독립)로 보고 두 시료의 복원값 차이가 오차보다 큰가를 본다. 논문의 통계 처리가 아니다.
"""
import numpy as np
from scipy.stats import norm
rmsep, lo, hi = 41, 85, 223
rng_range = hi - lo
print('=== 계산 4-6 (1) 복원 범위와 오차 ===')
print('복원 범위 %d~%d mm = %d mm 폭. 시료별 오차 41.7~51.7 mm' % (lo, hi, rng_range))
for s in (41.7, 43, 46, 51.7):
    d95 = 1.96 * np.sqrt(2) * s
    print('  시료별 오차 %.1f 일 때 두 시료의 차이가 95%%로 구별되려면 차이가 %.0f mm 이상(= 범위 폭의 %.0f%%)' % (s, d95, d95 / rng_range * 100))
print('  RMSEP 41 mm 는 현대 시료 강수 범위 65~328 mm(폭 263 mm)의 %.1f%% 이다. 논문이 적은 15.5%%(경사 길이 대비)와 같은 분모라면 폭은 %.0f mm 이어야 하며 263 mm 와 가깝다(논문의 경사 길이 정의는 이 책이 확인하지 못했다).' % (41 / 263 * 100, 41 / 0.155))
print('  연속성(continentality) 함수: RMSEP 6 °C 가 21.1%% 이면 폭 %.1f °C' % (6 / 0.211))
print('  RMSEP 41 mm 는 복원 범위 폭 138 mm 의 %.0f%%' % (41 / rng_range * 100))
print()
print('=== 계산 4-6 (2) 가장 건조한 시료와 가장 습한 시료는 구별되는가 ===')
for s in (41.7, 46, 51.7):
    z = (hi - lo) / (np.sqrt(2) * s)
    print('  시료별 오차 %.1f: 최대-최소 차 %d mm → z = %.2f, 양쪽 p = %.3f' % (s, rng_range, z, 2 * norm.sf(z)))
print('  (최대와 최소는 오차 때문에 부풀려진 극값일 수 있다: 많은 시료 중 고른 극값 쌍이다)')
print()
print('=== 계산 4-6 (3) 75개 시료에서 최대-최소 차이가 오차만으로 나오는 정도(시연) ===')
rng = np.random.default_rng(4106)
n = 75
for s in (43, 46):
    mx = []
    for _ in range(20000):
        x = rng.normal(0, s, n)
        mx.append(x.max() - x.min())
    mx = np.array(mx)
    print('  참값이 모두 같은 가상 호수에서 시료 75개의 최대-최소 차: 오차 %d mm 이면 중앙 %.0f, 95%%: %.0f~%.0f mm (논문 복원 범위 %d mm)' % (s, np.median(mx), *np.percentile(mx, [2.5, 97.5]), rng_range))
print('  → 복원 범위 138 mm 는 시료 오차만으로 생길 수 있는 최대-최소 차(95% 구간 160~283 mm)보다 작다. 즉 이 범위만으로는 참값의 변동과 오차를 가르기 어렵다. 논문은 시료별 오차를 감안하면 홀로세 변화가 유의하지 않다고 쓴다. 다만 복원값은 대개 평균 쪽으로 쏠려(일반적으로 알려진 성질) 폭이 줄어드므로 이 시연의 독립 오차 가정은 거칠다.')
print()
print('=== 계산 4-6 (4) 시간 해상도 ===')
print('퇴적 속도 10 년/cm, 시료 75개, 평균 시료 간격 약 210 년 → 시료 간격 약 %.0f cm' % (210 / 10))
print('늦은 빙기~홀로세(약 %.1f ka 까지) 75개 × 210 = %d 년' % (75 * 210 / 1000, 75 * 210))
