# -*- coding: utf-8 -*-
"""계산 4-7: 텔레츠코예(Teletskoye) 호수 두 코어의 연대-깊이 일관성(Rudaya 등 2016).
논문 숫자: Tel 2001-2004(173 cm, 330 m 수심): 14C 두 점 895 ± 45 BP(이끼, 96.5 cm), 1540 ± 25 BP(나무, 173 cm); 꽃가루 구역 PZ04-I ~500~1000 CE(173~115 cm),
PZ04-II ~1000~1820 CE(115~20 cm), PZ04-III 1820~2004 CE(20~0 cm). 평균 퇴적 속도 1.125 mm/년(합친 코어, 앞선 추정).
Tel 2006(194 cm, 90 m 수심): 표지층 38~39 cm 약 0.79~0.81 cal ka BP, PZ06-IV ~2280~830 cal BP, PZ06-V ~1120 CE~2006 CE(40~0 cm); 평균 퇴적 속도 0.45 mm/년(210Pb, 137Cs).
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import c14cal as C
def fmt(h):
    return ' ; '.join('%d~%d (%.1f%%)' % (a, b, m * 100) for a, b, m in h)
print('=== 계산 4-7 (1) Tel 2001-2004: 두 14C 점 보정 ===')
for lab, a, e, d in (('이끼', 895, 45, 96.5), ('나무', 1540, 25, 173)):
    s = C.summary(a, e)
    print('  %s %d ± %d BP, 깊이 %.1f cm → 평균 %.0f ± %.0f cal BP (= AD %.0f), 95.4%%: %s' % (lab, a, e, d, s['mean'], s['sd'], 1950 - s['mean'], fmt(s['hpd'])))
sm = C.summary(895, 45); sw = C.summary(1540, 25)
dt = sw['mean'] - sm['mean']
print('  두 점 사이: Δ깊이 %.1f cm, Δ연대 %.0f 년 → %.3f mm/년' % (173 - 96.5, dt, (173 - 96.5) * 10 / dt))
print('  표면에서 96.5 cm 까지(코어 위 2004 CE 가정): %.1f cm / %.0f 년 = %.3f mm/년' % (96.5, 1950 - 2004 + sm['mean'], 96.5 * 10 / (sm['mean'] + 54)))
print()
print('=== 계산 4-7 (2) 꽃가루 구역 경계에서 구한 퇴적 속도 ===')
Z = [('PZ04-I', 173, 115, 500, 1000), ('PZ04-II', 115, 20, 1000, 1820), ('PZ04-III', 20, 0, 1820, 2004)]
for n, d0, d1, y0, y1 in Z:
    print('  %-9s %3d→%3d cm (%d cm), %d→%d CE (%d 년): %.3f mm/년' % (n, d0, d1, d0 - d1, y0, y1, y1 - y0, (d0 - d1) * 10 / (y1 - y0)))
print('  세 구역 전체: 173 cm / %d 년 = %.3f mm/년 (논문의 앞선 추정 1.125 mm/년과 비교)' % (2004 - 500, 1730 / (2004 - 500)))
print('  구역 경계의 연대 모형으로 96.5 cm 의 연대를 예측: AD %.0f (보정한 이끼 연대 AD %.0f)' % (1000 + (115 - 96.5) / (95 / 820), 1950 - sm['mean']))
print('  173 cm 의 연대: 구역 경계 AD 500, 보정한 나무 연대 AD %.0f' % (1950 - sw['mean']))
print()
print('=== 계산 4-7 (3) Tel 2006 ===')
print('  표지층 38.5 cm / 0.80 ka = %.3f mm/년 (논문 평균 0.45 mm/년)' % (38.5 * 10 / 800))
print('  PZ06-V: 40→0 cm, 1120~2006 CE (%d 년): %.3f mm/년' % (2006 - 1120, 400 / (2006 - 1120)))
print('  PZ06-IV: 시작 2280 cal BP, 끝 830 cal BP (1450 년); 구역 깊이는 본문에서 읽지 못했다(PZ06-IV 는 약 40 cm 아래)')
print('  두 코어의 속도 비 1.125/0.45 = %.1f (같은 호수의 330 m 수심 대 90 m 수심 위치)' % (1.125 / 0.45))
print()
print('=== 계산 4-7 (4) 소빙기 구간과 시료 수 ===')
d = lambda yr: 115 - (yr - 1000) * 95 / 820   # PZ04-II 안의 선형 보간(cm)
print('  Tel 2001-2004 에서 1450~1800 CE(가장 서늘한 구간)은 깊이 약 %.0f~%.0f cm (구역 PZ04-II 속도 %.3f cm/년 사용)' % (d(1450), d(1800), 95 / 820))
print('  꽃가루 시료 간격 2.5 cm: 그 구간에는 약 %.0f 개 시료(= %.0f 년 / (%.1f 년/시료))' % ((1800 - 1450) / (2.5 / (95 / 820)), 1800 - 1450, 2.5 / (95 / 820)))
