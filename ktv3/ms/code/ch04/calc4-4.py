# -*- coding: utf-8 -*-
"""계산 4-4: 논문 초록과 본문이 적은 숫자로 하는 산수. (논문 값과 이 책이 나눈 값을 구분해 읽는다.)
(1) Tarasov 등(2009) 코토켈 호수의 기후 숫자를 차이로 옮긴다.
(2) Tarasov 등(1997) 오제르키 늪의 겨울 최저 기온 숫자.
(3) Wen 등(2010) 훌룬 호수의 시기 구분이 11,000년을 빈틈없이 덮는지.
(4) Rudaya 등(2009) 호톤 호수의 강수량 변화 비.
(5) Blyakharchuk 등(2004), Huang 등(2018), Dirksen 등(2007)의 시기 길이.
"""
import numpy as np
print('=== 계산 4-4 (1) 코토켈(Tarasov 등 2009): 차갑고 건조한 시기와 타이가 최대기 ===')
cold = dict(jul=12.0, jan=-38.0, pre=(270, 300))
max_ = dict(jul=(17, 18), jan=-19.0, pre=(500, 550))
print('차갑고 건조한 시기(13.5 ka 이전, 영거 드라이아스 12.8~11.6 ka): 7월 평균 약 %.0f °C, 1월 약 %.0f °C, 연강수 %d~%d mm' % (cold['jul'], cold['jan'], *cold['pre']))
print('타이가 최대기(10.8~7.3 ka): 7월 약 %d~%d °C, 1월 약 %.0f °C, 연강수 %d~%d mm' % (*max_['jul'], max_['jan'], *max_['pre']))
print('7월 기온 상승: %.0f~%.0f °C ; 1월 기온 상승: %.0f °C ; 강수량 증가: %d~%d mm (비 %.2f~%.2f 배)' % (
    max_['jul'][0] - cold['jul'], max_['jul'][1] - cold['jul'], max_['jan'] - cold['jan'],
    max_['pre'][0] - cold['pre'][1], max_['pre'][1] - cold['pre'][0], max_['pre'][0] / cold['pre'][1], max_['pre'][1] / cold['pre'][0]))
print('7월-1월 차(연교차): 차가운 시기 %.0f °C → 타이가 최대기 %.1f~%.1f °C : 줄어든 양 %.1f~%.1f °C' % (
    cold['jul'] - cold['jan'], max_['jul'][0] - max_['jan'], max_['jul'][1] - max_['jan'],
    (cold['jul'] - cold['jan']) - (max_['jul'][1] - max_['jan']), (cold['jul'] - cold['jan']) - (max_['jul'][0] - max_['jan'])))
print('→ 논문이 적은 숫자만 보면 1월 기온의 변화(+19 °C)가 7월(+5~6 °C)보다 컸다. 이 차이가 숲 확장의 원인이라는 해석은 이 책이 확인하지 않았다(초록 수준).')
print('타이가 최대기 길이 %.1f 천 년(10.8→7.3); 이후 감소 시작 7~6.5 ka: 최대기 끝과 감소 시작 사이 %.1f~%.1f 천 년' % (10.8 - 7.3, 7.3 - 7.0, 7.3 - 6.5))
print('숲(나무가 덮은 21×21 km 안의 면적 비율) 50%% 초과인 기간: 10.8~7.3 ka = %.0f 년' % ((10.8 - 7.3) * 1000))
print('보레알 삼림 교체 3회: 14.8~14.7, 13.3~12.8, 11.5~10.5 ka. 구간 길이: %.0f, %.0f, %.0f 년' % (100, 500, 1000))
print()
print('=== 계산 4-4 (2) 오제르키(Tarasov 등 1997) ===')
print('초기 홀로세 절대 최저 기온 -60 °C 미만, 현재보다 약 8 °C 낮음 → 현재 절대 최저 기온 약 %d °C 미만(논문 숫자로부터의 역산)' % (-60 + 8))
print('자작나무 급증 7800~7250 BP: 길이 %d 년; 소나무 확산 5800 BP 이후 → 자작나무 급증과 소나무 확산 사이 %d 년' % (7800 - 7250, 7250 - 5800))
print('늦은 빙기 몬타나 스텝-타이가 13,000~10,100 BP: 길이 %d 년' % (13000 - 10100))
print()
print('=== 계산 4-4 (3) 훌룬 호수(Wen 등 2010) 구간 합 ===')
W = [('11000~8000 건조 스텝', 11000, 8000), ('8000~6400 초본·자작나무 확장(강수 증가)', 8000, 6400), ('6400~4400 서늘하고 건조', 6400, 4400),
     ('4400~3350 명아주과 우세(극도 건조)', 4400, 3350), ('3350~2050 쑥 회복', 3350, 2050), ('2050~1000 쑥 감소·소나무 숲 확산', 2050, 1000), ('최근 1000년 사람 활동', 1000, 0)]
tot = 0
for n, a0, a1 in W:
    print('  %-42s %5d년' % (n, a0 - a1)); tot += a0 - a1
print('  합 = %d 년 (11,000~0 cal BP 를 빈틈, 겹침 없이 덮는다)' % tot)
print('  극도 건조 구간(4400~3350) 길이 %d 년 = 전체의 %.1f%%' % (4400 - 3350, (4400 - 3350) / 11000 * 100))
print('  8000 cal BP 이전 11,000~8000(%d년)이 건조 스텝 구간이다. 논문은 이를 근거의 하나로 여름 몬순이 8000 cal BP 이후에 강해졌다고 결론짓는다' % 3000)
print()
print('=== 계산 4-4 (4) 호톤 호수(Rudaya 등 2009) 강수량 ===')
lo0, hi0, lo1, hi1 = 200, 250, 450, 550
print('약 10 ka 전 강수량: %d~%d → %d~%d mm/년. 증가량 %d~%d mm, 비 %.2f~%.2f 배' % (lo0, hi0, lo1, hi1, lo1 - hi0, hi1 - lo0, lo1 / hi0, hi1 / lo0))
print('5 ka 이후 %d~%d mm/년: 최댓값 %d~%d 에서 감소량 %d~%d mm (비 %.2f~%.2f)' % (250, 300, 450, 550, 450 - 300, 550 - 250, 250 / 550, 300 / 450))
print('논문 서술: 10~5 ka 약 300~550 mm, 5 ka 이후 250~300 mm → 5 ka 전후 평균 차 약 %.0f mm' % (np.mean([300, 550]) - np.mean([250, 300])))
print()
print('=== 계산 4-4 (5) 다른 기록의 시기 길이 ===')
print('Blyakharchuk 등(2004): 짙은 침엽수림 확립 9.5 ka, 전나무·가문비나무 감소 7.5 ka → 사이 %.1f 천 년; 숲 형성 시작 약 12 ka → 확립까지 %.1f 천 년' % (9.5 - 7.5, 12 - 9.5))
print('Huang 등(2018): 상부 삼림대 숲 최대 10~7 ka(%d년), 7 ka 이후 냉각' % 3000)
print('Dirksen 등(2007): 건조기 11.7~7.6 ka(%.1f 천 년), 습한 두 번(5.1, 2.8 ka) 사이 %.1f 천 년, 7.6 ka 의 습윤 증가에서 사람 거주 시작 6 ka 까지 %.1f 천 년, 건조 간격 3.6~3.3 ka(%d 년)' % (11.7 - 7.6, 5.1 - 2.8, 7.6 - 6.0, 300))
print('Prokopenko 등(2007) 호브스골: 강수·유출 증가 11~7 ka(%d 년), 따뜻한 여름과 숲 감소 6~3.5 ka(%d 년)' % (4000, 2500))
