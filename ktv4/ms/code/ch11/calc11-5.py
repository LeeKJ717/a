# -*- coding: utf-8 -*-
"""계산 11-5: 수분(호수, 강수) 시간창의 비교와 마야 기록의 산술. 입력은 논문 초록의 숫자.
Baker 등(2001) 티티카카: 가장 건조 8.0~5.5 ka (cal yr BP). Shuman 등(2009) 로키산맥: 가장 심하고 넓은 저수위 7.0~4.5 ka, 콜로라도 습한 시기 4.4~3.7 ka, 약 3.0~2.0 ka 이전은 지금보다 건조한 곳이 많음.
Hobbs 등(2011) 노스다코타 케틀 호수: 습한 8.351~8.088, 4.364~1.406, 0.872~0.620 ka.
Kennett 등(2012): 기원후 440~660 높은 강수, 660~1000 건조화, 1020~1100 가뭄. Haug 등(2003): 가뭄 중심 810, 860, 910 년.
"""
def ov(a, b):
    return max(0.0, min(a[0], b[0]) - max(a[1], b[1]))
ti = (8.0, 5.5); ro = (7.0, 4.5); co = (4.4, 3.7)
H = [(8.351, 8.088), (4.364, 1.406), (0.872, 0.620)]
print('=== 길이(ka) ===')
print('티티카카 건조 %.2f, 로키 저수위 %.2f, 콜로라도 습윤 %.2f' % (ti[0] - ti[1], ro[0] - ro[1], co[0] - co[1]))
for h in H: print('케틀 호수 습윤 %.3f~%.3f 길이 %.3f' % (h[0], h[1], h[0] - h[1]))
print()
print('=== 겹침(ka) ===')
print('티티카카 건조(8.0~5.5)와 로키 저수위(7.0~4.5) 겹침 %.2f ka. 티티카카 창의 %.0f %%' % (ov(ti, ro), 100 * ov(ti, ro) / 2.5))
for i, h in enumerate(H):
    print('케틀 습윤%d 와 로키 저수위 겹침 %.3f / 티티카카 건조 겹침 %.3f / 콜로라도 습윤 겹침 %.3f' % (i + 1, ov(h, ro), ov(h, ti), ov(h, co)))
print('케틀 습윤2 (4.364~1.406) 길이 %.3f ka 가운데 콜로라도 습윤(4.4~3.7)과 겹치는 비율 %.0f %%' % (H[1][0] - H[1][1], 100 * ov(H[1], co) / (H[1][0] - H[1][1])))
print('8.2 ka 한랭 창(8.4~8.0, 5장)과 케틀 습윤1(8.351~8.088) 겹침 %.3f ka (케틀 창의 %.0f %%)' % (ov((8.4, 8.0), H[0]), 100 * ov((8.4, 8.0), H[0]) / (H[0][0] - H[0][1])))
print()
print('=== 마야(기원후) ===')
hi = (440, 660); dr = (660, 1000); dd = (1020, 1100)
print('높은 강수 %d 년, 건조화 %d 년, 가뭄 %d 년. 건조화 시작과 가뭄 시작 사이 %d 년' % (hi[1] - hi[0], dr[1] - dr[0], dd[1] - dd[0], dd[0] - dr[1]))
print('Haug 가뭄 중심 810, 860, 910: 간격 %d, %d 년. 모두 Kennett 건조화 창(660~1000) 안: %s' % (860 - 810, 910 - 860, all(dr[0] <= y <= dr[1] for y in (810, 860, 910))))
print('Kennett 높은 강수에서 건조화 시작까지 %d 년(440 에서 1000 까지 건조화 끝) = %d 년' % (dr[0] - hi[0], dr[1] - hi[0]))
