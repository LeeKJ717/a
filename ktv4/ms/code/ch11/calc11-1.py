# -*- coding: utf-8 -*-
"""계산 11-1: 북미 서부의 마자마 화산(오리건) 분화 연대와 재의 범위. 이 장이 읽은 아메리카 자료 가운데 숫자로 되풀이할 수 있는 것.
입력: Egan 등(2015, Holocene 25, 1054) 초록: 81개 방사성탄소 연대의 메타분석, 베이즈 95.4% 7682~7584 cal BP, GISP2 7627 ± 150 BP(Zdanowicz 등 1999를 Egan 등이 인용).
Sigl 등(2022): 5677 ± 150 BCE, 기원전 5922 ± 50(Khangar), 6440 ± 25(쿠릴 호수). 백과사전(이차 자료): 6790 ± 15 14C BP, 7640 ± 20 cal BP, 재 면적 최소 900,000 km²(David 1970 인용).
"""
import json, math
import numpy as np
out = {}
print('=== 계산 11-1 (1) 마자마 연대의 세 서술 ===')
egan = (7584, 7682)
print('  Egan 등(2015) 95.4%%: %d~%d cal BP (폭 %d년, 가운데 %.0f)' % (egan[0], egan[1], egan[1] - egan[0], sum(egan) / 2))
print('  Sigl 등(2022) 빙핵: 기원전 5677 ± 150 → %d ± 150 BP = %d~%d' % (5677 + 1950, 5677 + 1950 - 150, 5677 + 1950 + 150))
print('  백과사전(이차 자료): 7640 ± 20 cal BP → %d~%d' % (7620, 7660))
print('  세 구간의 폭: 98, 300, 40 년. Egan 구간 안에 백과사전 구간이 드는가: %s' % (egan[0] <= 7620 and 7660 <= egan[1]))
print('  백과사전 ±20과 논문 초록 구간 반폭 %.0f의 비 = %.2f (±20이 1σ이고 95.4%%가 2σ라면 2σ = ±40, 반폭 49와 %.0f년 차)' % ((egan[1] - egan[0]) / 2, 20 / ((egan[1] - egan[0]) / 2), 49 - 40))
print('  14C 연대와 보정 연대의 차: 7640 − 6790 = %d년(백과사전의 두 값, 이차 자료)' % (7640 - 6790))
out['egan'] = egan
print('\n=== 계산 11-1 (2) 재의 범위의 크기(이차 자료) ===')
A = 900000.0
r = math.sqrt(A / math.pi)
print('  면적 최소 %d km² → 같은 면적의 원 반지름 %.0f km (재가 원이 아니라 한쪽으로 길게 퍼졌다면 이 값은 실제 도달 거리와 다르다)' % (A, r))
print('  이 숫자는 이차 자료(백과사전이 David 1970을 인용)이고 이 장은 원전을 읽지 못했다.')
print('\n=== 계산 11-1 (3) 홀로세 초기 분화들의 빙핵 연대(Sigl 등 2022)와 오차 ===')
ev = [('Khangar', 5922, 50), ('Mazama', 5677, 150), ('쿠릴 호수', 6440, 25)]
for n, y, e in ev:
    print('  %-8s 기원전 %d ± %d → %d ± %d BP; 오차 비 %.2f%%' % (n, y, e, y + 1950, e, 100 * e / (y + 1950)))
print('  마자마와 Khangar의 가운데 차 = %d년, 두 오차의 제곱합 평균 = %.0f년 → %.1fσ (정규 가정, 두 오차가 독립이라 놓음)' % (5922 - 5677, math.hypot(50, 150), (5922 - 5677) / math.hypot(50, 150)))
json.dump(out, open('out/calc11-1.json', 'w'), ensure_ascii=False, indent=1)
