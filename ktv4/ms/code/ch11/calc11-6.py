# -*- coding: utf-8 -*-
"""계산 11-6: 해안과 빙상, 온난기의 산술. 입력은 논문 초록이 적은 숫자.
Engelhart와 Horton(2012) 미국 대서양 연안: 지표점 492, 한계 연대 344, 지역 16, 4 ka 이전 선형 상승 0.5~4.5 mm/yr, 4 ka~AD 1900 0.6~1.8 mm/yr.
Dalton 등(2020): 18 ka 빙상 면적 17.81 -> 18.37 백만 km2, 새 14C 연대 1541, 전체 5195.
Kaufman 등(2004): 140 지점 중 120 지점이 지금보다 따뜻, 정량 16 지점 평균 1.6±0.8 C, 알래스카와 북서 캐나다 11~9 ka, 북동 캐나다는 약 4000 년 뒤.
Angulo 등(2006): 해안 7000 km, 14C 시료 1000 개 이상, 14 구간, 30 % 자료가 점진적 하강.
"""
print('=== 미국 대서양 연안: 4 ka 이후 상승량(1900 AD = 50 BP 로 놓음) ===')
yrs = 4000 - 50
for r in (0.6, 1.8):
    print('%.1f mm/yr x %d 년 = %.2f m' % (r, yrs, r * yrs / 1000))
print('4 ka 이전 선형 상승 0.5~4.5 mm/yr 는 4장 Hijma 등 11~3 ka 평균 4.71 mm/yr 와 견줌: 상한 4.5 는 4.71 의 %.0f %%, 하한 0.5 는 %.0f %%' % (100 * 4.5 / 4.71, 100 * 0.5 / 4.71))
print('4 ka 이후 상한 1.8 mm/yr 는 4장 평균 4.71 의 %.0f %%' % (100 * 1.8 / 4.71))
print('지표점 492 대 한계 연대 344: 합 %d, 지표점 비율 %.1f %%. 지역당 평균 지표점 %.1f' % (492 + 344, 100 * 492 / (492 + 344), 492 / 16))
print()
print('=== 빙상 ===')
print('18 ka 빙상 면적 증가 %.2f 백만 km2 = %.2f %% (논문 3.1 %%)' % (18.37 - 17.81, 100 * (18.37 - 17.81) / 17.81))
print('새 연대 1541 / 전체 5195 = %.1f %%. 이전 자료 수 = %d' % (100 * 1541 / 5195, 5195 - 1541))
print()
print('=== 홀로세 온난기(북미 서부 북극) ===')
print('온난 지점 비율 120/140 = %.1f %%' % (100 * 120 / 140))
print('평균 1.6±0.8 C 범위 %.1f~%.1f C' % (1.6 - 0.8, 1.6 + 0.8))
print('알래스카·북서 캐나다 11~9 ka 와 북동 캐나다의 간격 약 4000 년(논문 서술): 북동 캐나다 최온난기는 7~5 ka 쯤이라는 산술(11-4000, 9-4000)')
print('Menounos 최소 빙하 11~7 ka(4.0 ka 창)와 겹침: 알래스카·북서 캐나다 온난기 11~9 ka 는 %.1f ka 겹침' % (min(11, 11) - 9))
print()
print('=== 브라질 해안 ===')
print('1000 시료 / 14 구간 = 구간당 %.0f 개 이상. 구간당 해안 길이 7000/14 = %.0f km' % (1000 / 14, 7000 / 14))
