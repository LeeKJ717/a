# -*- coding: utf-8 -*-
"""계산 4-2: 해수면 상승 속도의 산술. 논문 숫자만 사용.
Lambeck 등(2014): 약 16.5~8.2 ka 평균 약 12 m/ka; MWP-1A 14.5~14.0 ka, 속도 >=40 mm/yr.
Deschamps 등(2012): MWP-1A 시작 >=14,650, 끝 <14,310 yr 전(창 최대 340년); 타히티 상승 12~22 m(최확 14~18 m); 전지구 속도 >40 mm/yr.
Hijma 등(2025): 11~3 ka 전지구 평균 해수면 상승 37.7 m (2시그마 29.3~42.2); 가속 정점 약 10.3, 8.3 ka 에서 8~9 mm/yr.
"""
print('=== (1) MWP-1A 속도 ===')
win = 14650 - 14310
print('창 최대 길이 %d 년' % win)
for lab, h in (('12 m', 12), ('14 m', 14), ('18 m', 18), ('22 m', 22)):
    print('  타히티 %s / %d 년 = %.1f mm/yr' % (lab, win, h / win * 1000))
print('  (타히티 상승은 그 지점의 상대 값이며 전지구 평균 값이 아니다. Deschamps 는 전지구 속도를 >40 mm/yr 로 적었다.)')
print('  창이 더 짧으면 속도는 더 크다: 창 200 년이면 14~18 m 가 %.0f~%.0f mm/yr' % (14 / 200 * 1000, 18 / 200 * 1000))
print()
print('=== (2) 평균 12 m/ka 와의 비율 ===')
print('  40 mm/yr / 12 mm/yr = %.1f 배' % (40 / 12))
print('  12 m/ka x 8.3 ka (16.5->8.2 ka) = %.1f m' % (12 * 8.3))
print('  이 값에 MWP-1A 몫: 40 mm/yr x 0.3 ka(14.5~14.0 ka 중 최대 0.5 ka 가운데 0.3) = %.0f m (속도 하한 기준, 창 길이 가정은 시연값)' % (40 * 0.3))
print()
print('=== (3) Hijma 등(2025) 11~3 ka ===')
for lab, v in (('중앙', 37.7), ('하한', 29.3), ('상한', 42.2)):
    print('  %s %.1f m / 8 ka = %.2f mm/yr' % (lab, v, v / 8))
print('  가속 정점 8~9 mm/yr 는 11~3 ka 평균 %.1f mm/yr 의 %.1f~%.1f 배' % (37.7 / 8, 8 / (37.7 / 8), 9 / (37.7 / 8)))
print('  Lambeck 의 8.2~2.5 ka "느려짐" 구간과 겹치는 8.2~3 ka 평균은 이 표에서 직접 구할 수 없다(본문 값 없음).')
print()
print('=== (4) 한반도 값과의 속도 견줌(제1권 인용, 시연) ===')
# 제1권: Saito 1998: -40 m at 10 ka, present at 6-7 ka -> 
for lab, h, t0, t1 in (('Saito: -40 m(10 ka) -> 0(6.5 ka 가운데값)', 40, 10, 6.5), ('Saito: -40 m(10 ka) -> 0(6 ka)', 40, 10, 6.0), ('Saito: -40 m(10 ka) -> 0(7 ka)', 40, 10, 7.0)):
    print('  %s: %.1f mm/yr' % (lab, h / (t0 - t1)))
print('  Jo(1980) 동해안(14C 나이): -25 m(10 ka) -> -10 m(7 ka): %.1f mm/yr; -10 -> 0 (7 -> 6 ka): %.1f mm/yr' % (15 / 3, 10 / 1))
print('  Clark 모형(Bloom과 Park 경유, 남해): -31.7 m(9 ka) -> -12.2 m(7 ka): %.2f mm/yr; -12.2 -> -2.4 (7 -> 5 ka): %.2f mm/yr' % (19.5 / 2, 9.8 / 2))
print('  Bloom과 Park(서해): 1.6 mm/yr (8.6~4.8 ka) = %.1f m' % (1.6 * 3.8))
