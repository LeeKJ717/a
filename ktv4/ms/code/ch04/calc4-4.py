# -*- coding: utf-8 -*-
"""계산 4-4: Vacchi 등(2018)이 적은 지역별 상대 해수면 값으로 구간 속도와 감쇠 꼴 맞춤. 논문 숫자만.
단위: 연대 ka(보정 연대로 적힌 것으로 이 장은 취급, 원문 확인 필요), 높이 m(현재 해수면 기준).
"""
import numpy as np
S = {
 'SE 허드슨만(융기)': ([8.5, 7.5, 7.1, 6.4, 5.7, 3.5, 1.9], [289, 205, 177, 130, 105, 56, 30]),
 '동부 노바스코샤(침강)': ([8.3, 6.7, 4.2, 3.8, 1.7], [-34, -21, -9.9, -8.1, -3.3]),
 '세이블섬(침강)': ([9.0, 5.2, 4.4], [-35, -13.3, -10.9]),
 'NW 뉴펀들랜드': ([5.3, 1.7], [4.9, 2.4]),
}
print('=== (1) 구간 속도(mm/yr = m/ka) ===')
for k, (t, h) in S.items():
    print(k)
    for i in range(len(t) - 1):
        r = (h[i + 1] - h[i]) / (t[i] - t[i + 1])
        print('   %.1f -> %.1f ka: %+7.2f mm/yr' % (t[i], t[i + 1], r))
print()
print('=== (2) 평균 속도 ===')
print('SE 허드슨만 289/8.5 = %.1f, 56/3.5 = %.1f, 30/1.9 = %.1f mm/yr (논문: 최근 8 ka 약 35, 4 ka 약 15)' % (289 / 8.5, 56 / 3.5, 30 / 1.9))
print('노바스코샤 -34 -> -3.3 (8.3->1.7 ka) 평균 %+.2f mm/yr; 세이블 -35 -> -10.9 (9.0->4.4) %+.2f mm/yr' % ((-3.3 + 34) / 6.6, (-10.9 + 35) / 4.6))
print()
print('=== (3) 감쇠 꼴 h = A (exp(T/tau) - 1) 맞춤: SE 허드슨만 ===')
t, h = map(np.array, S['SE 허드슨만(융기)'])
from scipy.optimize import curve_fit
f = lambda T, A, tau: A * (np.exp(T / tau) - 1)
p, cov = curve_fit(f, t, h, p0=[100, 3.0])
res = h - f(t, *p)
print('A = %.1f m, tau = %.2f ka; 잔차 %s' % (p[0], p[1], np.round(res, 1)))
print('잔차 RMS %.1f m' % np.sqrt((res ** 2).mean()))
print('외삽 현재 속도 dh/dT(T=0) = A/tau = %.1f mm/yr (검증되지 않은 외삽; 자료점은 1.9 ka 가 가장 최근)' % (p[0] / p[1]))
print('비교: 스웨덴 북부 GIA 융기 약 9.6 mm/yr (Kierulf 2021, 최대 10.3 에서 탄성 0.7~0.8 뺌) -- 다른 지역이라 같은 지점 비교가 아니다.')
print('맞춤이 나쁘다: 1.9 ka 에서 모형 %.0f m, 자료 30 m. 외삽 속도는 믿을 수 없다. 부호: 허드슨만 속도는 상대 해수면의 하강(음), 노바스코샤와 세이블은 상승(양).' % f(1.9, *p))
print()
print('=== (4) 같은 시기(약 8.3 ka)의 지역 간 차이 ===')
print('SE 허드슨만 +289 m (약 8.5 ka), 노바스코샤 -34 m (8.3 ka). 높이 차이 약 %d m (200년 안팎 차이는 무시)' % (289 + 34))
print('먼 곳(far-field) 8 ka 부근 값은 이 장이 가진 논문 숫자 안에 없다: Lambeck 의 8.2~2.5 ka 느려짐 서술만 있음.')
print('Vacchi 가 적은 속도: 초기 최대 약 17 mm/yr, 중기 약 9, 후기 2 미만(어느 지역 값인지 이 장이 확인하지 못함). SE 허드슨만 최근 8 ka 평균 35 mm/yr 는 17 의 %.1f 배.' % (35 / 17))
