"""계산 4-3: Hijma와 Cohen(2010, 라인강 삼각주) 8.2 ka 부근 해수면 도약의 산술. 논문 숫자만.
논문 값: 시작 8450+-44 년 전; 도약 2.11+-0.89 m (200년 안); 배경 상승 1.95+-0.74 m; 두 표본 사이 합 4.06+-0.50 m (표본 간격 195+-68 년);
배경 속도 10+-1.5 mm/yr; 전지구 도약 3.0+-1.2 m (약 70% 환산); 부피 10.7+-4.5 x 10^14 m3; 이전 추정 0.4~1.4 m; 배경만으로 설명될 확률 약 10%.
"""
import numpy as np
from math import erf, sqrt
print('=== (1) 합산과 환산 ===')
print('2.11 + 1.95 = %.2f m (논문 4.06)' % (2.11 + 1.95))
print('오차 제곱합 sqrt(0.89^2+0.74^2) = %.2f m (논문 합의 오차 0.50 은 이 값보다 작다. 이유는 논문 본문을 읽지 못해 확인 필요)' % sqrt(0.89 ** 2 + 0.74 ** 2))
print('2.11 / 0.70 = %.2f m (논문 3.0)' % (2.11 / 0.70))
print('3.0 m x 3.61e14 m2 = %.2e m3 (논문 10.7e14 의 %.0f%%)' % (3.0 * 3.61e14, 3.0 * 3.61e14 / 10.7e14 * 100))
print('10.7e14 m3 / 3.61e14 m2 = %.2f m' % (10.7e14 / 3.61e14))
print('부피 4.5e14 오차 -> %.2f m' % (4.5e14 / 3.61e14))
print()
print('=== (2) 속도 ===')
print('도약 2.11 m / 200 yr = %.1f mm/yr (배경 10 mm/yr 위에 겹친 것이 아니라 도약 값만)' % (2.11 / 200 * 1000))
print('배경 10 mm/yr x 195 yr = %.2f m (논문 배경 1.95)' % (10e-3 * 195))
print('도약+배경 4.06 m / 195 yr = %.1f mm/yr' % (4.06 / 195 * 1000))
print('도약 3.0 m(전지구)/ 200 yr = %.1f mm/yr' % (3.0 / 200 * 1000))
print('이전 추정 0.4~1.4 m 대비 3.0 m 는 %.1f~%.1f 배' % (3.0 / 1.4, 3.0 / 0.4))
print()
print('=== (3) 배경만으로 4.06 m 가 되는가: 독립 정규 가정(시연) ===')
# 배경 속도 10+-1.5 mm/yr, 간격 195+-68 yr. 몬테카를로로 4.06 이상이 나올 확률
rng = np.random.default_rng(4)
n = 2_000_000
rate = rng.normal(10, 1.5, n) * 1e-3
dt = rng.normal(195, 68, n)
h = rate * dt
print('배경 1.95 m 의 몬테카를로 평균 %.2f, 표준편차 %.2f (논문 0.74)' % (h.mean(), h.std()))
print('배경만으로 도약 2.11 m 이상이 더해진 4.06 m 에 도달할 확률(시연): P(h>=4.06) = %.4f' % (h >= 4.06).mean())
z = (4.06 - 1.95) / 0.74
print('정규 근사 z = %.2f, P = %.4f' % (z, 0.5 * (1 - erf(z / sqrt(2)))))
print('논문은 "약 10%" 라고 적었다. 이 장의 시연은 0.2~0.6% 로 크게 어긋난다. 논문은 다른 오차 모형(표본 높이 오차, 압밀 보정 등)을 썼을 것이며 이 장은 그것을 재현하지 못했다.')
