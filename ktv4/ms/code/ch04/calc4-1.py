# -*- coding: utf-8 -*-
"""계산 4-1: 마지막 빙기 최성기의 얼음 부피와 해수면 상당량(ESL), 논문 값끼리의 견줌.
논문 숫자: Lambeck 등(2014) 해수면 −134 m(29~21 ka), 얼음 부피 현재보다 약 52 x 10^6 km3 더 많음.
Clark와 Tarasov(2014): 발표된 추정 105~163 m, Lambeck 134~140 m, 남극 23 m, 북미 간 차이 약 27 m.
Saito(1998, 제1권 인용): 최저 해수준 −120 +- 10 m. Lewis 등(2013): 약 125 m 아래(21~19 ka).
일반 상수(이 장에서 논문으로 확인하지 못함): 얼음 밀도 917 kg/m3, 해수 밀도 1027 kg/m3, 바다 면적 3.61 x 10^8 km2.
"""
import numpy as np
print('=== 계산 4-1 (1) 얼음 부피 -> 해수면 상당량(ESL) ===')
V = 52e6                    # km3, Lambeck 등(2014)
rho_i, rho_w, A = 917.0, 1027.0, 3.61e8
esl = V * (rho_i / rho_w) / A * 1000.0     # m
print('52 x 10^6 km3 x (917/1027) / 3.61 x 10^8 km2 = %.1f m' % esl)
print('논문 값 134 m 와의 차 %.1f m (%.1f%%). 이 한 줄 환산은 바다 면적이 일정하고 해수 밀도가 일정하다고 놓은 것이며, 빙상 아래 지각의 조절과 해저 면적 변화는 들어 있지 않다.' % (134 - esl, (134 - esl) / 134 * 100))
for dens in (900, 917, 930):
    print('   얼음 밀도 %d 이면 %.1f m' % (dens, V * (dens / rho_w) / A * 1000))
print('   바다 면적이 3.5 / 3.7 x 10^8 km2 이면 %.1f / %.1f m' % (V * (rho_i / rho_w) / 3.5e8 * 1000, V * (rho_i / rho_w) / 3.7e8 * 1000))
print()
print('=== (2) 논문들의 최성기 해수면 값을 한 줄에 ===')
vals = [('Lambeck 등(2014)', 134, 134), ('Clark와 Tarasov(2014)가 정리한 발표 범위', 105, 163), ('Lambeck 등의 추정(같은 논평)', 134, 140), ('Lewis 등(2013), 호주 둘레(21~19 ka)', 125, 125), ('Saito(1998), 제1권 1.3절 A 입장', 110, 130), ('Ohshima(1990), 제1권: 3.5만 년 전 이전의 최저값(최성기 값 아님)', 75, 85)]
for nm, a, b in vals:
    print('%-44s %3d~%3d m' % (nm, a, b))
print('Lambeck 134 m 와 Saito 120 +- 10 m 의 차: %d m = Saito 오차 10 m 의 %.1f배. (Saito 는 외해 값이며 육지에 가까운 곳은 수압지각평형으로 얕아진다고 적었다.)' % (134 - 120, 14 / 10))
print('Lambeck 134 와 Lewis 125 의 차: %d m.  발표 범위 폭 %d m 는 134 m 의 %.0f%%.' % (134 - 125, 163 - 105, (163 - 105) / 134 * 100))
print()
print('=== (3) 얼음 덩어리별 몫(Clark와 Tarasov 2014가 적은 숫자) ===')
print('남극 23 m 는 134 m 의 %.0f%%. 북미 추정끼리의 차이 약 27 m 는 134 m 의 %.0f%%. 그린란드와 유라시아는 논문들 사이 차이가 2~4 m.' % (23 / 134 * 100, 27 / 134 * 100))
print('남극 몫만 빼면 나머지 %d m. 남극 값이 다른 재구성보다 높다는 서술은 논평이 적은 것이며 이 장이 시험하지 못했다.' % (134 - 23))
