# -*- coding: utf-8 -*-
"""계산 9-1: HolVol v1.0(Sigl 등 2022, ESSD 14, 3167)이 본문에 적은 숫자끼리의 산술 점검.
입력은 모두 논문 본문(요약 도구가 돌려준 값)의 숫자이다. 이 스크립트는 그 숫자들이 서로 맞는지만 본다.
"""
import json, math
import numpy as np
from scipy import stats
out = {}
print('=== 계산 9-1 (1) 기간과 빈도 ===')
n850, n1189 = 850, 1189
cum_all, cum_850, cum_abs = 7412.0, 7260.0, 7410.0
yrs_a = 9500 + 1900          # 기원전 9500년에서 기원후 1900년까지, 0년을 하나로 센 길이(해 수)
yrs_b = 9500 + 1900 - 1      # 0년이 없는 역사 달력으로 센 길이
yrs_c = 11500                # 논문 제목의 '지난 11 500년'
for lab, y in (('9500 BCE~1900 CE, 0년을 둠', yrs_a), ('0년이 없는 달력', yrs_b), ('제목의 11,500년', yrs_c)):
    print('  %-26s %6d 년: 850개/년 = %.4f 개/년 (%.1f 년에 한 번), 7260/세기 = %.2f, 7412/세기 = %.2f Tg S, 7410/세기 = %.2f' % (
        lab, y, n850 / y, y / n850, cum_850 / (y / 100), cum_all / (y / 100), cum_abs / (y / 100)))
out['freq_a'] = n850 / yrs_a; out['per_century_850_11400'] = cum_850 / (yrs_a / 100); out['per_century_850_11500'] = cum_850 / (yrs_c / 100)
print('  논문: 평균 빈도 0.074/년(약 14년에 한 번), 홀로세 평균 63 Tg S/세기')
print('  1189개 중 1 Tg S 이하 = %d개(%.1f%%); 이 개수의 누적 = %.0f Tg S (%.2f Tg S/개); 850개 평균 = %.2f Tg S/개' % (
    n1189 - n850, 100 * (n1189 - n850) / n1189, cum_all - cum_850, (cum_all - cum_850) / (n1189 - n850), cum_850 / n850))
out['mean_850'] = cum_850 / n850
print('\n=== 계산 9-1 (2) 백분율 서술의 되풀이 ===')
r_eh, r_late = 76.0, 45.0
print('  76 → 45 Tg S/세기: 비 %.3f, 감소 %.1f%% (논문 41%%)' % (r_late / r_eh, 100 * (1 - r_late / r_eh)))
print('  90 대 63: +%.1f%% (논문 43%%)' % (100 * (90 / 63 - 1)))
print('  조용한 시기(기원전 4000~1000): 63 × (1 − 0.36) = %.1f Tg S/세기, 3000년 합 = %.0f Tg S' % (63 * 0.64, 63 * 0.64 * 30))
print('  중기 홀로세 활동기: 63 × 1.22 = %.1f Tg S/세기' % (63 * 1.22))
dap_total = 90 * 25
print('  초기 홀로세 활동기(기원전 9500~7000, 2500년): 90 × 25세기 = %.0f Tg S = 전체 7412의 %.1f%%' % (dap_total, 100 * dap_total / cum_all))
print('  "초기 홀로세는 최근 2500년보다 개수 16%% 많고 VSSI 86%% 많다": 개당 평균 VSSI 비 = 1.86/1.16 = %.2f' % (1.86 / 1.16))
late2500 = dap_total / 1.86
print('  → 최근 2500년의 누적은 %.0f Tg S, 곧 %.1f Tg S/세기 (논문의 4천년기 이후 45 Tg S/세기와 같은 자릿수)' % (late2500, late2500 / 25))
out['late2500_per_century'] = late2500 / 25; out['dap_total'] = dap_total
print('  최근 2500년의 개수 = DAP 개수/1.16. 개수는 논문에 없으므로 구하지 않는다.')
print('\n=== 계산 9-1 (3) 발생 위치 서술끼리의 어긋남 ===')
print('  초록: 저위도 329 + 북반구 중고위도 426 + 남반구 중고위도 88 = %d (850과 %d 차이)' % (329 + 426 + 88, 850 - (329 + 426 + 88)))
for k, v in (('저위도', 329), ('북반구 중고위도', 426), ('남반구 중고위도', 88)):
    print('    %s %d / 850 = %.1f%%' % (k, v, 100 * v / 850))
print('  본문 3.1절 개수 비율 40 + 5(아이슬란드) + 45 + 10 = %d%%; 북반구 중고위도에 아이슬란드를 합하면 %d%%(초록 50%%과 맞음)' % (40 + 5 + 45 + 10, 45 + 5))
print('  초록 질량 비율: 열대 70%%, 북반구 중고위도 25%%; 본문: 열대 75%%, 아이슬란드 4%%+중고위도 18%% = %d%%' % (4 + 18))
print('  7260 × 0.70 = %.0f, 7260 × 0.75 = %.0f Tg S (열대의 질량이 두 서술에서 %.0f Tg S 달라짐)' % (7260 * 0.70, 7260 * 0.75, 7260 * 0.05))
print('  총량 서술: 초록 7410, 본문 7412, 850개분 7260')
print('\n=== 계산 9-1 (4) 가장 큰 10개 가운데 8개가 기원전 6700~4300년에 있다 ===')
w = 6700 - 4300; p = w / yrs_a
pv = stats.binom.sf(7, 10, p)
print('  창 길이 %d 년 = 전체 %d 년의 %.3f. 10개가 시기와 무관하게 흩어진다면 기대 %.2f개' % (w, yrs_a, p, 10 * p))
print('  이항분포 P(X >= 8; n = 10, p = %.3f) = %.2e' % (p, pv))
print('  홀로세 초기에 분화가 많았다는 점(계산 9-1 (1))을 감안하면 p를 키워야 한다. 창의 비율 p를 0.4, 0.5로 놓으면 P(X>=8) = %.3f, %.3f' % (stats.binom.sf(7, 10, 0.4), stats.binom.sf(7, 10, 0.5)))
out['binom_p'] = p; out['binom_pv'] = pv
print('\n=== 계산 9-1 (5) 분화 간격과 푸아송 기준선 ===')
lam = n850 / yrs_a
print('  λ = %.4f /년. 평균 간격 %.1f 년' % (lam, 1 / lam))
for g in (77,):
    pg = math.exp(-lam * g)
    print('  간격 >= %d 년일 확률 exp(−λg) = %.4f, 850개 간격 가운데 기대 개수 = %.1f' % (g, pg, n850 * pg))
    out['gap77_prob'] = pg; out['gap77_expected'] = n850 * pg
em = math.log(n850) / lam
print('  푸아송이라면 최대 간격의 기대(근사) ln(N)/λ = %.0f 년. 논문의 최대 간격 77 년은 이보다 짧다' % em)
out['expected_max_gap'] = em
print('  100년 동안 1 Tg S 넘는 분화가 한 번도 없을 확률 exp(−100λ) = %.5f' % math.exp(-100 * lam))
print('  100년 동안 기대 분화 수 = %.2f' % (100 * lam))
# 317년 간격(10 Tg S 넘는 것)에서 개수 역산: 최대 간격 ≈ ln(N)/λ10, λ10 = N/yrs
from scipy.optimize import brentq
f = lambda N: yrs_a * math.log(N) / N - 317
Nn = brentq(f, 5, 3000)
print('  [역산] 10 Tg S 넘는 분화 개수 N이 푸아송일 때 최대 간격 317년이 되려면 N ≈ %.0f개 (이 책의 역산이며 논문 값이 아님)' % Nn)
out['N10_inverted'] = Nn
print('\n=== 계산 9-1 (6) 연대 오차 창과 이웃 분화의 수 ===')
for lab, sd in (('최근 2500년 ±1~5년', 5), ('그 밖의 홀로세 ±5~15년', 15), ('WD2014 3000 BCE까지 ±20년', 20), ('기원전 9500년 ±66년', 66)):
    print('  %-30s ±%d 년 창(길이 %d 년)에 드는 다른 분화의 기대 수 = %.2f' % (lab, sd, 2 * sd, lam * 2 * sd))
    out['neighbors_%d' % sd] = lam * 2 * sd
print('  이 숫자는 전 홀로세 평균 빈도로 계산한 것이다. 초기 홀로세는 평균보다 잦으므로(90/63배) 더 크다: ±66년 창에서 %.2f' % (lam * 2 * 66 * 90 / 63))
print('\n=== 계산 9-1 (7) eVolv2k(Toohey & Sigl 2017)와 HolVol의 크기 견주기 ===')
print('  eVolv2k 장기 평균 VSSI 약 0.5 Tg S/년 = %.0f Tg S/세기. HolVol 홀로세 평균 63, 기원전 4천년기 이후 45 Tg S/세기 → 비 %.2f, %.2f' % (0.5 * 100, 50 / 63, 50 / 45))
print('  eVolv2k 세기당 사건 10.6개(IVI2 6.7개) → 비 %.2f. HolVol 세기당 %.1f개(1 Tg S 넘는 것). 두 편찬본의 문턱과 기간이 달라 개수를 곧바로 견줄 수 없다' % (10.6 / 6.7, 100 * 850 / 11400))
print('  eVolv2k 20세기 평균 VSSI는 500 BCE~1900 CE 평균보다 25%% 낮고 SAOD는 14%% 낮다: 0.5 × 0.75 = %.3f Tg S/년' % (0.5 * 0.75))
json.dump(out, open('out/calc9-1.json', 'w'), ensure_ascii=False, indent=1)
