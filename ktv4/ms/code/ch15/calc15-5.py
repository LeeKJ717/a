# -*- coding: utf-8 -*-
"""계산 15-5: "한 사건이 연대 오차 때문에 흩어져 보인다"는 설명은 얼마나 큰 오차를 요구하는가.
입력(8장): 둥거 동굴 후기 홀로세 쇠퇴 시작 3550 ± 59 yr BP(Dykoski 등 2005, 오차는 1시그마로 읽음). 메갈라야절 시작 4200 BP. Railsback 등 창 중심 4070.
서아시아 점추정 평균 4185 ± 45(제3권 6장). 8장이 적은 오차들: 나미비아 DP1 우라늄-토륨 10~28 년, ODP 658C 종료 연대 ± 190(6장), 둥거 59.
(a) 둥거와 기준점 사이의 z 와 95% 로 메우는 데 필요한 오차. (b) 8장이 적은 오차로 메울 수 있는가. (c) 일곱 창에 필요한 창 확장(계산 15-2 (d)와 같은 값)."""
import numpy as np, json
D, sD = 3550.0, 59.0
refs = [('메갈라야절 시작 4200 (점, 오차 모름)', 4200.0, 0.0), ('Railsback 등 창 중심 4070 (점, 오차 모름)', 4070.0, 0.0), ('서아시아 점추정 평균 4185 ± 45', 4185.0, 45.0)]
print('=== 계산 15-5 (a) 둥거 3550 ± 59 와 기준점의 거리 ===')
out = {}
for nm, t, s in refs:
    dlt = t - D; sc = np.hypot(sD, s); z = dlt / sc
    need = dlt / 2.0     # 95%(2시그마)로 메우는 데 필요한 둥거 쪽 오차(기준점은 오차 0 으로 두고 둥거만 키움)
    print('  %-42s 차 %4.0f 년, 합친 오차 %.1f, z = %.1f; 2시그마로 메우려면 오차가 %.0f 년(둥거의 %.1f 배)' % (nm, dlt, sc, z, need, need / sD))
    out[nm] = dict(delta=dlt, z=float(z), need=float(need), ratio=float(need / sD))
print()
print('=== 계산 15-5 (b) 8장이 적은 오차로 메울 수 있는가 ===')
for nm, e in (('나미비아 DP1 U-Th 최대 28 년', 28.0), ('둥거 59 년', 59.0), ('ODP 658C 종료 ± 190 년', 190.0)):
    print('  %-26s 2시그마 = %4.0f 년. 650 년의 %.0f%%, 520 년의 %.0f%%' % (nm, 2 * e, 100 * 2 * e / 650, 100 * 2 * e / 520))
print('  8장이 적은 가장 큰 오차(190)의 2시그마 380 년도 650 년과 520 년에 모자란다. 이 비교는 오차들이 같은 종류(방사성탄소 대 우라늄-토륨)가 아님을 무시한 거친 것이다.')
print()
print('=== 계산 15-5 (c) 일곱 창에 필요한 창 확장 ===')
print('  계산 15-2 (d): 창 양쪽을 37.5 년씩 넓히면 일곱 창이 처음 겹친다. 이는 둥거를 메우는 데 필요한 오차(260~325 년)의 %.0f%%~%.0f%%' % (100 * 37.5 / 325, 100 * 37.5 / 260))
print('  37.5 년은 나미비아 DP1 의 U-Th 오차 10~28 년의 %.1f~%.1f 배로 같은 자릿수이다. 유라시아 공통 구간(4025~3970)과 북미 중부 창(4300~4100)의 간격 75 년은 연대 오차 규모로 메워질 수 있는 크기이다(오차를 1시그마로 읽었을 때 창 양쪽에 각각 37.5 년).' % (37.5 / 28, 37.5 / 10))
print('  둥거와 4.2 ka 창의 650 년 간격은 그렇지 않다. 이 둘은 다른 종류의 어긋남이다.')
json.dump(out, open('calc15-5-out.json', 'w'), ensure_ascii=False)
