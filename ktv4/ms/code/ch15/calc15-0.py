"""계산 15-0: 쟁점 후보 셋의 "어긋남의 크기"를 앞 장 로그의 숫자로 나란히 놓는다(15.1절의 선택 근거).
후보 A: 8장 4.2 ka 창의 공통 구간(계산 8-4). 후보 B: 4장 얼음 부피 환산 128.6 m 대 134 m(계산 4-1). 후보 C: 9장 HolVol 본문 숫자(계산 9-1).
입력은 모두 앞 장의 로그에 있는 숫자이다. B의 역산 두 줄은 4장 입력(52e6 km3, 917/1027, 3.61e8 km2)만 쓴다."""
import numpy as np
print('=== 계산 15-0 (A) 8장: 공통 구간이 어느 창을 넣느냐에 따라 ===')
from windows15 import *
vals = {}
vals['다섯 창 전부'] = inter(GLOBAL5)[2]
for d in GLOBAL5:
    vals[d + ' 뺌'] = inter([n for n in GLOBAL5 if n != d])[2]
for k, v in vals.items(): print('  %-28s %5.0f 년' % (k, v))
mx, mn = max(vals.values()), min(vals.values())
print('  공통 구간 최대 %.0f, 최소 %.0f, 비 %.1f 배. 일곱 창까지 넓히면 %.0f 년(음수 = 공통 구간 없음)' % (mx, mn, mx / mn, inter(ALL7)[2]))
print()
print('=== 계산 15-0 (B) 4장: 얼음 부피 환산 128.6 m 대 논문 134 m ===')
V, A = 52e6, 3.61e8; ri, rw = 917.0, 1027.0
esl = V * (ri / rw) / A * 1000
print('  환산 %.1f m, 논문 134 m, 차 %.1f m (%.1f%%)' % (esl, 134 - esl, (134 - esl) / 134 * 100))
A_need = V * (ri / rw) / 134.0 * 1000   # km2
print('  [역산] 134 m 가 되려면 바다 면적이 %.3e km2 이어야 하고, 이는 3.61e8 의 %.1f%% (차 %.1f%%)' % (A_need, 100 * A_need / A, 100 * (1 - A_need / A)))
V_need = 134.0 / 1000 * A / (ri / rw)
print('  [역산] 면적을 3.61e8 로 두면 얼음 부피가 %.2f x 10^6 km3 여야 하고, 52 의 %.1f%%' % (V_need / 1e6, 100 * V_need / V))
print('  이 책에는 최성기의 바다 면적도 얼음 밀도의 논문 값도 없다. 역산은 "얼마가 필요한가"만 알려 준다.')
print()
print('=== 계산 15-0 (C) 9장: HolVol 본문 숫자의 불일치(로그 계산 9-1에서) ===')
print('  위치별 개수 329 + 426 + 88 = %d, 850 과 %d 차이(%.2f%%)' % (329 + 426 + 88, 850 - 843, 100 * 7 / 850))
print('  열대 질량 비율 70%% 대 75%%: 7260 Tg S 기준 %.0f Tg S 차이 (총량의 %.1f%%)' % (7260 * 0.05, 5.0))
print('  세기당 63.7 대 63.1: 차 %.2f Tg S/세기 (%.1f%%)' % (63.68 - 63.13, 100 * (63.68 - 63.13) / 63.13))
print('  세 불일치 모두 5% 이하이다. 어느 것이 반올림이고 어느 것이 정의의 차이인지는 논문 원문 표가 있어야 가른다.')
print()
print('=== 계산 15-0 (D) 세 후보의 크기 요약 ===')
print('  A: 공통 구간이 %.0f 년(창 5개 중 하나를 빼면 %.0f~%.0f 년)부터 %.1f 배까지 달라지고 일곱 창이면 없다' % (vals['다섯 창 전부'], mn, mx, mx / mn))
print('  B: 4.0%% 차이. 바다 면적이 %.1f%% 작으면 닫힌다(입력 하나의 값만 바뀌면 되는 크기)' % (100 * (1 - A_need / A)))
print('  C: 0.8%(개수), 5.0%(열대 질량 비율 차), 0.9%(세기당)')
