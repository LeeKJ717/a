# -*- coding: utf-8 -*-
"""계산 10-4: 논문들이 적은 주기와 상관 숫자의 산술 비교.
입력: Steinhilber 등(2012) 본문의 주기(드 브리스 약 210, 약 350, 약 500, 약 710, 에디 약 1000, 드 브리스 진폭의 약 2200년), 첫 주성분 설명 분산 69%.
Usoskin 등(2016): 홀레하임 약 2400년(2000~3000 결맞음), 두 이차 SSA 성분의 상관 0.77 ± 0.01, 필요한 쌍극자 변화 약 2×10^22 A m²(약 20%), 10Be 1σ 7%, 10Be 연대 조정 ±40년.
Vecchio 등(2017, A&A 599, A58) 초록: 슈바베 약 14년(마운더, 돌턴 극소기), 글라이스베르크 60~120년, 쥐스 약 200~300년, 홀레하임 약 2000년, 비태양 성분 약 7000년.
Debret 등(2007): 1000, 2500년을 태양, 1500년을 해양. Bond 등(2001): 홀로세 주기 평균 1340년, 주기 번호 0~8(아홉 개), 핵종-해양 상관 r = 0.44~0.56, 두 핵종 r = 0.6, HSG-10Be 결맞음 0.75(300~500년)와 0.93(900~1100년), HSG-14C 0.84, 0.23(비유의).
"""
import json
import numpy as np
out = {}
print('=== 계산 10-4 (1) 홀레하임 주기의 값 ===')
vals = {'Steinhilber 등(2012) 드 브리스 진폭 주기': 2200, 'Usoskin 등(2016) 홀레하임': 2400, 'Debret 등(2007) 태양 쪽 진동': 2500, 'Vecchio 등(2017) 홀레하임': 2000}
v = np.array(list(vals.values()), float)
for k, x in vals.items():
    print('  %-42s %d년' % (k, x))
print('  네 값의 범위 %d~%d, 평균 %.0f, 최대/최소 = %.2f' % (v.min(), v.max(), v.mean(), v.max() / v.min()))
out['hall_range'] = [float(v.min()), float(v.max())]
print('  Usoskin 등(2016)의 결맞음 구간 2000~3000년의 폭은 중심 2500의 ±%.0f%%' % (100 * 500 / 2500))
print('\n=== 계산 10-4 (2) 짧은 주기와의 비 ===')
for a, b, n in ((2200, 210, '홀레하임(2200)/드 브리스(210)'), (2400, 210, '홀레하임(2400)/드 브리스(210)'), (2200, 1000, '홀레하임(2200)/에디(1000)'), (2400, 1000, '홀레하임(2400)/에디(1000)'), (1000, 210, '에디(1000)/드 브리스(210)'), (1500, 1000, 'Bond 1500/에디 1000'), (1500, 2500, 'Bond 1500/태양 2500')):
    print('  %-32s %.2f' % (n, a / b))
print('  정수비에 가까운 쌍이 없다. 정확한 정수 배 관계는 논문이 주장하지 않는다.')
print('\n=== 계산 10-4 (3) 상관 계수가 가리키는 겹치는 분산 ===')
for n, r in (('Usoskin 등(2016) 두 SSA 성분', 0.77), ('Bond 등(2001) 핵종-해양 하한', 0.44), ('Bond 등(2001) 핵종-해양 상한', 0.56), ('Bond 등(2001) 두 핵종', 0.6)):
    print('  %-32s r = %.2f → r² = %.2f (겹치는 분산 %.0f%%)' % (n, r, r * r, 100 * r * r))
print('  Steinhilber 등(2012): 첫 주성분이 전체 분산의 69%, 공통 신호 약 70%, 나머지 약 30%는 시스템 효과')
print('  Bond 등(2001)의 결맞음: HSG-10Be 0.75(300~500년), 0.93(900~1100년), HSG-14C 0.84, 그리고 14C 서브천년 0.23(비유의)')
out['r2'] = {'usoskin': 0.77 ** 2, 'bond_lo': 0.44 ** 2, 'bond_hi': 0.56 ** 2, 'bond_nuc': 0.36}
print('\n=== 계산 10-4 (4) 쌍극자 대안 ===')
dip = 2e22; frac = 0.20
print('  Usoskin 등(2016): 홀레하임을 지자기만으로 만들려면 쌍극자 변화 약 %.0e A m²(약 %.0f%%)가 필요 → 기준 쌍극자 %.1e A m²를 함의' % (dip, 100 * frac, dip / frac))
print('  논문 서술: 어떤 지자기 재구성도 이를 지지하지 않는다')
print('\n=== 계산 10-4 (5) 불확도 숫자 ===')
print('  10Be 1σ 7%%: 값이 100이면 ±7. 10Be 연대 조정 ±40년은 10년 해상도에서 %d칸' % (40 / 10 * 2 + 1))
print('  Usoskin 등(2016) 1000 실현 × 10Be 앙상블 → 10^6 계열')
print('\n=== 계산 10-4 (6) Bond 등(2001) 주기 수 ===')
print('  평균 1340년 × 주기 9개(0~8) = %d년. 요약 도구가 돌려준 서술("센테니얼 주기를 0~9000년 전에 놓았다")의 9000년을 1340년으로 나누면 %.1f주기' % (1340 * 9, 9000 / 1340))
print('  어느 쪽이 맞는지는 원문(그림 2와 4의 설명)을 직접 봐야 한다. 이 책이 읽은 쪽은 PDF 추출문이라 기호가 깨져 있다.')
print('\n=== 계산 10-4 (7) Vecchio 등(2017)의 슈바베 주기 이동 ===')
print('  11년(Brehm 등 2021의 슈바베 주기) 대 극소기의 약 14년: %.0f%% 길다(%.2f배)' % (100 * (14 / 11 - 1), 14 / 11))
json.dump(out, open('out/calc10-4.json', 'w'), ensure_ascii=False, indent=1)
