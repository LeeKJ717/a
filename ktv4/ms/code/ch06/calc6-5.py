"""계산 6-5: 동굴 석순이 그린 몬순 사건의 간격, 지속, 덮는 시간 (Dykoski 등 2005, Wang 등 2005, Fleitmann 등 2003, 2007).
입력(논문): Dongge: 양의 δ18O 사건 중심 11225+-97(1.05‰), 10880+-117(1.15‰), 9165+-75(1.4‰), 8260+-64(1.1‰)와 8080+-74(1.0‰) 이중, 3550+-59 yr BP 의 급한 양의 이동(약 100 년에 1.1‰);
 Wang 등: 9000년 기록에 약한 몬순 사건 8개, 각 1~5 세기; Fleitmann 등(2003): 기록 10.3~2.7 ky 와 1.4~0.4 ky; 8 ky 이후 서서히 감소; 2007: 4개 동굴, 12~23°N."""
import numpy as np
from scipy import stats
ev = [('A', 11225., 97.), ('B', 10880., 117.), ('C', 9165., 75.), ('D1', 8260., 64.), ('D2', 8080., 74.)]
print('[A] Dongge 양의 δ18O 사건 사이 간격 (오차는 두 중심의 제곱합 제곱근, 1표준편차로 가정)')
for (n1, a1, s1), (n2, a2, s2) in zip(ev[:-1], ev[1:]):
    d = a1-a2; sd = np.hypot(s1, s2)
    print('   %s -> %s: 간격 %5.0f +- %3.0f 년 (z=%.1f)' % (n1, n2, d, sd, d/sd))
print('   이중 사건 중심의 가운데 = %.0f, 간격 180 +- 98: 0 과의 차 z=%.2f, p=%.3f' % ((8260+8080)/2, 180/np.hypot(64, 74), 2*(1-stats.norm.cdf(180/np.hypot(64, 74)))))
print()
print('[B] 3550 +- 59 의 급한 이동과 4.2 ka 의 거리')
for ref, nm in ((4200., '메갈라야 경계 4250 yr b2k = 4200 cal BP'), (4260., 'Carolin 등 골에자르드 시작'), (3930., 'Railsback 등 경계 후단')):
    print('   %s: 차 %4.0f 년 (3550 의 오차 59 의 %.1f 배)' % (nm, ref-3550, (ref-3550)/59))
print('   초록이 말하는 범위에서 후기 홀로세 몬순 쇠퇴의 시작은 3.55 ka 의 이동이다. 4.2 ka 즈음 사건의 유무는 초록만으로 알 수 없다')
print()
print('[C] Wang 등(2005): 9000 년 동안 약한 몬순 사건 8개, 각 100~500 년')
n, T = 8, 9000.
print('   사건 빈도 = 1 / %.0f 년' % (T/n))
for L in (100., 300., 500.):
    print('   사건 길이 %3.0f 년이면 기록의 %.1f %% 가 사건' % (L, 100*n*L/T))
print('   즉 사건이 기록의 %.0f~%.0f %% 를 차지한다. 앞 사건 간격 평균 %.0f 년, 사건 길이 3~5 세기이면 사건 사이의 조용한 기간은 평균 %.0f~%.0f 년' % (100*n*100/T, 100*n*500/T, T/n, T/n-500, T/n-100))
print()
print('[D] Fleitmann 등(2003) 석순의 덮는 시간')
a1 = 10.3-2.7; a2 = 1.4-0.4
print('   덮는 길이 %.1f + %.1f = %.1f ky, 빈틈 2.7~1.4 = %.1f ky, 전체 10.3~0.4 = %.1f ky 중 %.0f %%' % (a1, a2, a1+a2, 2.7-1.4, 10.3-0.4, 100*(a1+a2)/(10.3-0.4)))
print('   4.2 ka 는 덮은 구간 안(10.3~2.7)에 있고, 8.2 ka 도 안에 있다')
print('   Fleitmann 등(2007): 4개 동굴 12~23°N, 위도 폭 %d 도 = 약 %d km' % (23-12, (23-12)*111))
print()
print('[E] Dongge 사건 8260 +- 64 대 Cheng 등(2009) 8.21 ka 시작, GRIP 최소 8.21 +- 0.03 ka')
for nm, v, s in (('Cheng 등 시작', 8210., None), ('Alley 등 GRIP 최소', 8210., 30.)):
    s2 = np.hypot(64, s) if s else 64.
    print('   %s: Dongge D1 와의 차 %.0f 년, z=%.2f (오차 %s)' % (nm, 8260-v, (8260-v)/s2, '합성' if s else 'Dongge 만'))
