"""계산 6-8: deMenocal 등(2000) 플럭스 표의 내부 일치 점검.
플럭스 = 성분 비율 x 전체 플럭스여야 한다. 표 2의 값(요약 도구가 돌려준 것)이 서로 맞는지 점검해 요약의 신뢰도를 본다.
입력(g/cm2/ka): 구간별 (육상 기원 플럭스, 비율), (탄산염 플럭스, 비율), 오팔 플럭스, 전체 플럭스."""
rows = {'0~5.2 ka': dict(t=(11.22, .60), c=(6.46, .34), o=1.06, tot=18.75),
        '5.3~14.8 ka': dict(t=(7.64, .45), c=(8.45, .49), o=1.04, tot=17.12),
        '17.2~26.0 ka': dict(t=(8.30, .59), c=(5.3, .37), o=0.54, tot=14.15)}
for k, r in rows.items():
    t_fl, t_pc = r['t']; c_fl, c_pc = r['c']
    print('[%s]' % k)
    print('  육상 기원: 비율 x 전체 = %.2f x %.2f = %.2f (표 %.2f, 차 %+.2f, %.1f %%)' % (t_pc, r['tot'], t_pc*r['tot'], t_fl, t_fl-t_pc*r['tot'], 100*(t_fl-t_pc*r['tot'])/t_fl))
    print('  탄산염   : 비율 x 전체 = %.2f x %.2f = %.2f (표 %.2f, 차 %+.2f, %.1f %%)' % (c_pc, r['tot'], c_pc*r['tot'], c_fl, c_fl-c_pc*r['tot'], 100*(c_fl-c_pc*r['tot'])/c_fl))
    s = t_fl+c_fl+r['o']
    print('  세 성분 합 %.2f 대 전체 %.2f (차 %+.2f)' % (s, r['tot'], s-r['tot']))
    print('  표의 비율로 역산한 오팔 몫: %.1f %%, 오팔 플럭스/전체 = %.1f %%, 비율 합 육상+탄산염 = %.0f %%' % (100*(1-t_pc-c_pc), 100*r['o']/r['tot'], 100*(t_pc+c_pc)))
print()
print('코어 전체 평균 조성(논문): 탄산염 42 %%, 오팔 5 %%, 육상 53 %%; 합 = %d %%' % (42+5+53))
print('세 구간의 비율(육상, 탄산염) 평균: 육상 %.1f %%, 탄산염 %.1f %% (구간 길이로 가중하지 않은 단순 평균)' % (100*(.60+.45+.59)/3, 100*(.34+.49+.37)/3))
