"""계산 6-2: deMenocal 등(2000) ODP 658C 코어의 숫자를 다시 계산하고 CLIMBER-2 종료 연대(Claussen 등, 1999)와 견준다.
입력은 두 논문이 적은 숫자뿐이다. 논문 값은 '논문', 이 계산의 값은 '계산'으로 표시한다."""
import numpy as np
print('[A] 플럭스 변화율 다시 계산 (g/cm2/ka, 논문 표 2와 4.1절)')
fl = {'육상기원 5.3~14.8 -> 0~5.2 ka': (7.64, 11.22, '+47 %'),
      '탄산염   5.3~14.8 -> 0~5.2 ka': (8.45, 6.46, '-24 %'),
      '탄산염 17.2~26.0 -> 5.3~14.8 ka (논문 5.31 -> 8.5)': (5.31, 8.5, '+59 %'),
      '육상기원 17.2~26.0 -> 5.3~14.8 ka (논문 8.3 -> 7.6)': (8.3, 7.6, '-8 %')}
for k, (a, b, p) in fl.items():
    print('  %-52s %.2f -> %.2f = %+.1f %%  (논문 %s)' % (k, a, b, 100*(b-a)/a, p))
print('  참고: 표의 탄산염 5.3~14.8 ka 8.45 와 본문의 8.5 는 반올림 차이다. 8.45 로 17.2~26.0 ka 5.3 과 견주면 %+.1f %%' % (100*(8.45-5.3)/5.3))
print()
print('[B] 시료 간격과 종료 해상도')
sr = 18.0      # cm/ka, 논문 평균
sub = 2.0      # cm, 연속 시료 간격
dt = sub/sr*1000
print('  2 cm / 18 cm/ka = %.0f 년 (논문: 50~150 년, 초록 약 100 년)' % dt)
for sr2 in (13.3, 18.0, 40.0):
    print('    퇴적률 %.1f cm/ka 이면 시료 간격 %.0f 년' % (sr2, sub/sr2*1000))
print('  탄산염 시료 227개 x %.0f 년 = %.1f ka (논문: 지난 약 25 cal ka)' % (dt, 227*dt/1000))
print('  습윤기 길이 14.8 - 5.5 = %.1f ka -> 시료 약 %.0f 개' % (9.3, 9300/dt))
print('  종료 400년 미만 -> 시료 최대 %.1f 개, 코어 길이 %.1f cm' % (400/dt, 0.4*sr))
print('  종료 중심 5490 +- 190 은 시료 간격(%.0f)의 %.1f 배' % (dt, 190/dt))
print('  14C 연대 18개로 지난 23 ka: 평균 간격 %.2f ka' % (23/18))
print('  빈틈 17.20~14.80 = %.2f ka, 코어 328 cm(17.21) 와 324 cm(14.69) 사이 4 cm: 퇴적률 %.2f cm/ka' % (17.20-14.80, 4/(17.21-14.69)))
print('  저수지 보정 500년 대 평균 400년: 연대가 %d 년 어긋나면 종료 연대도 같은 방향으로 %d 년' % (100, 100))
print()
print('[C] CLIMBER-2 종료(5440 +- 30, 앙상블 10) 와 코어(5490 +- 190)')
d = 5490-5440; sd = np.hypot(190, 30)
z = d/sd
from scipy import stats
print('  차 %d, 합성 오차 %.1f, z=%.2f, p=%.2f' % (d, sd, z, 2*(1-stats.norm.cdf(abs(z)))))
print('  모형 앙상블 오차(30)는 코어 오차(190)의 %.0f %%. 모형은 10개 실행의 흩어짐이고 자료의 불확실성이 아니다' % (100*30/190))
print('  모형 민감도 실행: 현재 해수면 온도·해빙 5.8 ka, 중기 홀로세 해수면 온도·해빙 5.3 ka -> 폭 %.1f ka' % (5.8-5.3))
print('  모형의 급변 구간 약 300 년(식생율 약 0.3 감소). 코어의 종료 < 400 년과 같은 크기')
