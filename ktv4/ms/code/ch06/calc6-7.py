# -*- coding: utf-8 -*-
"""계산 6-7: 기록의 시료 간격과 사건 길이: 한 사건에 시료가 몇 개 들어가는가.
입력(논문): ODP 658C 시료 간격 111년(계산 6-2, 논문 50~150년), 카리아코 2 mm = 4~5년(Haug 등), 둥거 5년 해상도(Wang 등)와
 δ18O 900개 이상이 16 ka(Dykoski 등), 서아프리카 연안 코어 3~4 cm(퇴적률 요약에 없음).
사건 길이는 이 장이 다룬 값: 100, 200, 300, 400(deMenocal 종료 상한), 500년(Wang 등 사건 상한)."""
import numpy as np
rec = {'ODP 658C 먼지': 111., '카리아코 Ti(2 mm)': 4.5, '둥거 Wang 등(5년 해상도)': 5.0, '둥거 Dykoski 등(900개/16 ka)': 16000/900.}
L = [100, 200, 300, 400, 500]
print('사건 안의 시료 수 = 사건 길이 / 시료 간격')
print('%-30s %6s ' % ('기록', '간격') + ' '.join('%6d' % l for l in L) + '   시료 2개를 담는 가장 짧은 사건')
for k, d in rec.items():
    print('%-30s %6.1f ' % (k, d) + ' '.join('%6.1f' % (l/d) for l in L) + '   %6.0f 년' % (2*d))
print()
print('Dykoski 등: 900개 이상이 16 ka -> 평균 간격은 17.8년 이하(실제는 900개 이상이므로 더 촘촘)')
print()
print('14C 연대 점 사이 간격(연대가 실제로 잡힌 곳)')
for k, n, T in (('ODP 658C 14C 18개/23 ka', 18, 23000), ('카리아코 14C 10개/14 ka', 10, 14000), ('둥거 230Th 45개/16 ka', 45, 16000)):
    print('  %-28s 평균 간격 %5.0f 년' % (k, T/n))
print()
print('해석: 시료 간격은 촘촘해도 연대 점 사이는 보간이다. 사건의 길이를 연대 점 간격과 견주면')
for k, n, T in (('ODP 658C', 18, 23000), ('카리아코', 10, 14000), ('둥거', 45, 16000)):
    d = T/n
    print('  %-8s 연대 점 간격 %5.0f 년: 400년 사건은 간격의 %.0f %%, 100년 사건은 %.0f %%' % (k, d, 400/d*100, 100/d*100))
