"""계산 6-4: Haug 등(2001) 카리아코 분지 티타늄(Ti) 기록의 해상도와 경향을 논문 숫자로 다시 계산.
입력(논문): 코어 상부 5.5 m 가 지난 14 ky; 침적률 ~30 cm/ky; 2 mm 간격 = 4~5 년; 14C 10개; Ti 지난 8 ky 동안 약 50% 감소;
 건조 경향 시작 ~5.4 ka; 극소 중심 ~3.8, 3.4, 3.0, 2.8 ka; 소빙기 극소 550~200 년 전(세 극소)."""
import numpy as np
print('[A] 시료 간격 점검')
L, T = 550.0, 14.0     # cm, ky
mean_rate = L/T
print('  평균 침적률 = 550 cm / 14 ky = %.1f cm/ky' % mean_rate)
print('  2 mm 간격 = %.1f 년 (평균 침적률 기준)' % (0.2/mean_rate*1000))
for r in (30.0, 40.0, 50.0):
    print('  침적률 %.0f cm/ky 이면 2 mm = %.1f 년' % (r, 0.2/r*1000))
print("  논문의 '~30 cm/ky' 이면 2 mm 는 %.1f 년으로 4~5 년과 맞지 않는다. 4~5 년이 되려면 40~50 cm/ky 가 필요하다(홀로세 구간의 높은 침적률 또는 반올림)." % (0.2/30*1000))
print('  14C 10개 / 14 ky = 평균 간격 %.2f ky. 시료 간격(4.5 년)의 %.0f 배. 연대 점 사이는 선형 보간이라는 가정이 필요' % (14/10, 1400/4.5))
print()
print('[B] Ti 감소 경향 (지난 8 ky 약 50%)')
print('  직선이면 처음 값의 %.2f %%/ky, 지수 감소이면 %.2f %%/ky (반감기 8 ky)' % (50.0/8.0, -np.log(0.5)/8.0*100))
print('  어느 쪽이든 100 년에 처음 값의 1 %% 이내(직선 %.2f %%, 지수 %.2f %%)이다. 시료 간격 4~5 년에 견주면 한 시료 당 변화는 %.3f %%' % (50/8/10, -np.log(0.5)/8*10, 50/8/1000*4.5))
print()
print('[C] 극소 간격')
m = np.array([3.8, 3.4, 3.0, 2.8])
d = -np.diff(m)
print('  극소 중심 %s ka, 간격 %s ka, 평균 %.0f 년' % (m, d, d.mean()*1000))
print('  4개 극소가 놓인 구간 %.1f ky (3.8~2.8). 이 구간은 4.2 ka 사건(4.3~3.9 ka)보다 젊다. 4.2 ka 즈음의 극소는 이 책이 읽은 범위에 없음' % (3.8-2.8))
print('  소빙기 극소 550~200 년 전 = 길이 %d 년, 세 극소' % (550-200))
print()
print('[D] 8.3~7.8 ka 극소의 길이 %.1f ky. 5.4 ka 이후 건조 경향 시작과 deMenocal 등(2000)의 종료 5.49 +- 0.19 ka 의 차 %d 년(오차 190 안)' % (8.3-7.8, 5490-5400))
