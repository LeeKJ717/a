# -*- coding: utf-8 -*-
"""계산 6-6: Tierney 등(2017) 잎 왁스 강수 복원의 숫자 점검.
입력(논문): 초록 지점 전체 중앙값 약 640 mm/yr (1표준편차 250~1670), 현재 서부 사하라 35~100 mm/yr, 31°N 중앙값 1280 (560~2550),
 19°N 볼링-알레뢰드 중앙값 1430 (623~2740), 강수와 δDP 는 로그 정규 관계 r 약 -0.72, 8 ka 강수 감소 19~23°N 에서 적어도 약 1000 년, Gobero 점유 공백 8150~7150 yr BP."""
import numpy as np
print('[A] 중앙값과 1표준편차 범위가 로그 대칭인지')
for nm, med, lo, hi in (('전체', 640., 250., 1670.), ('31°N', 1280., 560., 2550.), ('19°N BA', 1430., 623., 2740.)):
    up, dn = hi/med, med/lo
    print('  %-8s 상한/중앙 %.2f, 중앙/하한 %.2f, 로그 sigma 약 %.2f (상·하 평균), 기하 평균 %.0f' % (nm, up, dn, np.log((up*dn)**0.5), np.sqrt(lo*hi)))
print('  전체는 거의 로그 대칭(2.61 대 2.56)이고 31°N 와 19°N 는 상한/중앙이 중앙/하한보다 약간 작다(중앙값이 기하 평균보다 위쪽). 선형 대칭이면 640 +- 710 이 되어 하한이 음수라 불가능')
print()
print('[B] 현재 대비 배율')
print('  640 / (35~100) = %.1f ~ %.1f 배 (논문: 약 10 배)' % (640/100, 640/35))
print('  1280 / (35~100) = %.1f ~ %.1f 배' % (1280/100, 1280/35))
print('  전체 중앙값의 1시그마 하한 250 도 현재 상한 100 의 %.1f 배' % (250/100))
print()
print('[C] 1시그마 범위의 절대 폭: 전체 %d, 31°N %d, 19°N BA %d mm/yr (중앙값이 클수록 넓다, 논문도 같은 말). 상대 폭(폭/중앙): %.2f, %.2f, %.2f 로 단조롭지 않다' % (1670-250, 2550-560, 2740-623, 1420/640, 1990/1280, 2117/1430))
print()
print('[D] 8 ka 중단과 Gobero')
print('  Gobero 공백 8150 ~ 7150 = %d 년 (논문: 적어도 약 1000 년)' % (8150-7150))
print('  공백의 시작 8150 은 Dongge 이중 사건의 두 중심 8260 +- 64 와 8080 +- 74 사이에 놓인다. 두 기록이 같은 사건을 본다고 말하려면 연대 오차(64, 74)와 복원 연대 오차(논문 요약에 없음)를 알아야 한다')
