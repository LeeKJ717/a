# -*- coding: utf-8 -*-
"""계산 5-1: 8.2 ka 부근 호수 방류의 부피를 유량(스베드럽, Sv)으로 바꾸는 산술.
Hijma와 Cohen(2010): 전지구 도약 부피 10.7+-4.5 x 10^14 m3 (환산 후 값), 도약은 200년 안, 합산 4.06 m 는 두 표본 사이 195+-68 년.
1 Sv = 10^6 m3/s, 1년 = 3.156e7 s (이 책의 상수).
주의: 이 부피는 로테르담 해수면 도약을 전지구로 환산한 값이며 호수 방류의 직접 측정이 아니다. 200년은 해수면 도약의 지속이지 방류의 지속이 아니다.
"""
YR = 3.156e7
def sv(vol_m3, years):
    return vol_m3 / (years * YR) / 1e6
print('=== (1) 부피 -> Sv (지속 200년) ===')
for lab, v in (('중앙 10.7e14', 10.7e14), ('하한 6.2e14', 6.2e14), ('상한 15.2e14', 15.2e14)):
    print('  %s m3 / 200 yr = %.3f Sv' % (lab, sv(v, 200)))
print()
print('=== (2) 지속 시간을 바꾸면(시연) ===')
for d in (50, 100, 195, 200, 340, 500):
    print('  지속 %3d 년: %.3f Sv (중앙 부피)' % (d, sv(10.7e14, d)))
print()
print('=== (3) 해수면 환산 ===')
A = 3.61e14
print('  3.0 m x 3.61e14 m2 = %.2e m3' % (3.0 * A))
print('  유량 0.17 Sv 를 1년 쌓으면 %.2e m3 = 해수면 %.1f mm' % (0.17e6 * YR, 0.17e6 * YR / A * 1000))
print()
print('=== (4) 로테르담 도약 속도와 같은 비교 ===')
print('  전지구 3.0 m / 200 년 = %.1f mm/yr -> %.3f Sv' % (3.0 / 200 * 1000, 3.0 / 200 * A / YR / 1e6))
print('  (3)과 (1)이 같은 값(0.17 Sv 부근)이 나오는 것은 같은 부피를 같은 시간으로 나눈 것이므로 독립 확인이 아니다.')
