# -*- coding: utf-8 -*-
"""계산 5-2: 4장의 해수면 상승 속도를 담수 유량(Sv)으로 환산. 바다 전체(3.61e8 km2, 이 책의 상수)에 고르게 퍼진다고 놓은 ESL 환산.
모든 속도는 4장이 논문에서 옮긴 숫자이며, 유량은 얼음이 녹아 바다에 더해진 물이 그만큼이라는 가정 위의 평균이다(바닷물의 열팽창, 땅 위 물 저장 변화 등은 넣지 않음).
"""
YR = 3.156e7; A = 3.61e14
def sv(mm_yr):
    return mm_yr * 1e-3 * A / YR / 1e6
rows = [('MWP-1A 전지구 속도의 하한(Deschamps 등, Lambeck 등)', 40), ('타히티 14 m / 340 년(4장 계산)', 41.2), ('타히티 18 m / 340 년', 52.9),
        ('Lambeck 등 16.5~8.2 ka 평균', 12), ('Hijma 등 두 가속 정점 8', 8), ('Hijma 등 두 가속 정점 9', 9), ('Hijma 등 11~3 ka 평균', 4.71),
        ('남극 기여 평균 하한(4장 계산 4-5)', 0.51), ('남극 기여 평균 상한', 1.03), ('Lambeck 등 6 ka 이후 진동 한계 0.75', 0.75), ('같은 한계 1.0', 1.0)]
print('=== 해수면 속도 -> 담수 유량 ===')
print('1 mm/yr = %.5f Sv' % sv(1))
for lab, r in rows:
    print('%-52s %6.2f mm/yr = %.4f Sv' % (lab, r, sv(r)))
print()
print('=== 같은 단위의 비교 ===')
print('MWP-1A 하한 / 평균 12 mm/yr = %.1f 배' % (sv(40) / sv(12)))
print('8.3 ka 로테르담 도약 환산 0.17 Sv(계산 5-1) 는 11~3 ka 평균 %.3f Sv 의 %.1f 배' % (sv(4.71), 0.17 / sv(4.71)))
print('8.3 ka 로테르담 도약 0.17 Sv 는 가속 정점 8~9 mm/yr (%.3f~%.3f Sv) 의 %.1f~%.1f 배' % (sv(8), sv(9), 0.17 / sv(9), 0.17 / sv(8)))
print('대서양 자오선 순환(AMOC)의 세기는 이 장이 논문에서 확인하지 못했다. 그래서 위 유량을 AMOC 의 몇 %로 나타내지 못한다.')
