# -*- coding: utf-8 -*-
"""계산 5-5: 논문 초록이 적은 시간창(ka BP)을 한 표에 놓고 길이와 겹침을 센다. 논문 숫자만 사용(가공 없음).
출처: Gerber 등(2025) AMOC 약화 9.2~8 ka, 안정 6.5 ka 이후 / Hoogakker 등(2011) 북동대서양 깊은 물 유속 감소 6.5 ka 이후 / Barber 등(1999) 방류 8,470 cal yr, 한랭 사건 8.4~8.0 /
Hijma와 Cohen(2010) 8450±44 / Emile-Geay 등 ENSO 분산 감소 5~3 ka(64 %) / Carré 등(2014) 억제 5~4 ka, 서늘 편향 7.5~6.7, 현대형 확립 4.5~3 / Conroy 등(2008) 강수 강도 4.2±0.13 이후, 정점 2.0±0.1~1.5±0.07 / Moy 등(2002) 사건 증가 약 1.2 ka 까지.
"""
W = {
 'AMOC 약화(Gerber 2025)': (9.2, 8.0),
 'AMOC 안정(Gerber 2025)': (6.5, 0.0),
 '깊은 물 유속 감소(Hoogakker 2011)': (6.5, 0.0),
 '한랭 사건(Barber 1999)': (8.4, 8.0),
 'ENSO 분산 감소(Emile-Geay)': (5.0, 3.0),
 'ENSO 억제(Carré 2014)': (5.0, 4.0),
 '페루 서늘 편향(Carré 2014)': (7.5, 6.7),
 '현대형 확립(Carré 2014)': (4.5, 3.0),
 '강수 강도 증가(Conroy 2008)': (4.2, 0.0),
 '강수 정점(Conroy 2008)': (2.0, 1.5),
 'ENSO 사건 증가(Moy 2002)': (12.0, 1.2),
}
def ov(a, b):
    lo = min(a[0], b[0]); hi = max(a[1], b[1])
    return max(0.0, lo - hi)
print('=== 시간창 길이(ka) ===')
for k, (a, b) in W.items():
    print('%-34s %5.1f ~ %-4.1f  길이 %.1f ka' % (k, a, b, a - b))
print()
print('=== AMOC 쪽 ===')
g = W['AMOC 약화(Gerber 2025)']
print('Barber 방류 8.47 ka 는 Gerber 약화창 안: %s, 창 시작(9.2)보다 %.2f ka 뒤' % (g[1] <= 8.47 <= g[0], 9.2 - 8.47))
print('한랭 사건 8.4~8.0 은 약화창(1.2 ka)의 %.0f %%' % (100 * 0.4 / 1.2))
print('Hijma와 Cohen 8.450±0.044: %.3f~%.3f ka, 약화창 안: %s' % (8.450 - 0.044, 8.450 + 0.044, g[1] <= 8.450 - 0.044 and 8.450 + 0.044 <= g[0]))
print('Gerber 안정 시작 6.5 ka 와 Hoogakker 유속 감소 시작 6.5 ka 는 같은 숫자지만 한쪽은 안정, 한쪽은 감소를 말함(측정량이 다름: 231Pa/230Th 환산 유량 대 퇴적물 입도 유속)')
print()
print('=== ENSO 쪽 겹침(ka) ===')
E = W['ENSO 분산 감소(Emile-Geay)']
for k in ('ENSO 억제(Carré 2014)', '현대형 확립(Carré 2014)', '강수 강도 증가(Conroy 2008)'):
    print('Emile-Geay 감소창(5~3)과 %-30s 겹침 %.1f ka' % (k, ov(E, W[k])))
c4 = 4.2
print('Conroy 4.2±0.13: %.2f~%.2f ka 이후 강수 증가. Emile-Geay 감소창 안(5~3)에 시작점이 들어감: %s' % (c4 - 0.13, c4 + 0.13, 3.0 <= c4 <= 5.0))
print('Moy 사건 증가는 약 1.2 ka 까지 이어졌다고 하나 Emile-Geay 5~3 ka 에 64 %% 감소, Carré 5~4 ka 억제를 보고: 같은 시기 겹침 %.1f ka (방향이 엇갈림)' % ov(E, W['ENSO 사건 증가(Moy 2002)']))
print('Cobb 등(2013): 산호 7 ka 전부, 체계적 추세 없음(같은 7 ka 에 위 연구들의 변화 창이 모두 들어감)')
print('Conroy 정점 2.0±0.1~1.5±0.07 ka 는 Moy 사건 증가 기간(~1.2 ka 까지) 안: %s' % (W['강수 정점(Conroy 2008)'][1] >= 1.2))
