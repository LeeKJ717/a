print()
print('[C] 그린란드 평균(%.0f 년)에 견준 다른 기록의 비' % g.mean())
for nm, lo, hi in (('Morrill 유럽 온도', 100, 160), ('Morrill 강수 대부분', 100, 150), ('Morrill 스웨덴', 30, 50), ('Morrill 아시아 몬순', 230, 280), ('Kleiven 심층수 감소', 100, 110), ('Ellison 동쪽 월류', 400, 400), ('Rohling 세계 기록 이상', 400, 600)):
    print('  %-22s %3d~%3d 년 -> %.2f ~ %.2f 배' % (nm, lo, hi, lo/g.mean(), hi/g.mean()))
