# -*- coding: utf-8 -*-
"""계산 1-3: 퇴적물 속 생물 뒤섞임(bioturbation)이 한 시료가 덮는 시간과 짧은 사건의 크기를 얼마나 깎는가.
입력(논문 값): Zuhr 등(2022, 남중국해 상자 코어) 혼합층 두께 8.4 ± 1.2 cm(눈으로 판정), 동위원소 비교로는 7.5~11 cm, 초록은 약 10 cm.
  퇴적 속도 3.4 cm/kyr(위쪽 10~18 cm), 1.6 cm/kyr(18 cm 아래). 같은 깊이 층 안의 방사성탄소 나이 퍼짐 최대 1,250 년,
  일반 연대 모형 오차는 최대 250 년, 그 논문은 실제 불확실성이 보통 가정의 약 5배라고 적었다.
Marcott 등(2013): 백색잡음 시험에서 300년보다 짧은 주기는 거의 남지 않고, 1000년 주기는 약 50%, 2000년보다 긴 주기는 거의 다 남는다.
아래의 모의는 시연이다(혼합을 같은 폭의 이동평균으로 근사한 것이며 논문의 모형이 아니다).
"""
import numpy as np
print('=== 계산 1-3 (1) 혼합층 두께를 퇴적 속도로 나눈 시간(한 시료가 섞고 있는 시간의 규모) ===')
for L, v, lab in ((8.4, 3.4, '눈 판정 8.4 cm, 위쪽 3.4 cm/kyr'), (10.0, 3.4, '약 10 cm, 위쪽 3.4 cm/kyr'), (7.5, 3.4, '동위원소 7.5 cm'), (11.0, 3.4, '동위원소 11 cm'),
                  (10.0, 1.6, '약 10 cm, 아래쪽 1.6 cm/kyr'), (8.4, 1.6, '눈 판정 8.4 cm, 아래쪽 1.6 cm/kyr')):
    print('  %-34s -> %.0f 년' % (lab, L / v * 1000))
print('  1 cm 두께 조각이 덮는 시간: 3.4 cm/kyr 에서 %.0f 년, 1.6 cm/kyr 에서 %.0f 년' % (1 / 3.4 * 1000, 1 / 1.6 * 1000))
print('  Zuhr 등: 같은 층 안 나이 퍼짐 최대 1250 년 / 일반 연대 모형 오차 최대 250 년 = %.1f 배 (논문은 약 5배라고 적음)' % (1250 / 250))
print()
print('=== 계산 1-3 (2) 이동평균(폭 W)이 160년짜리 사건과 사인파를 깎는 정도 ===')
print('160년짜리 직사각 사건의 최대 진폭이 폭 W 이동평균 뒤에 남는 비율 = min(1, 160/W)')
for W in (50, 160, 300, 600, 1000, 2000, 2500, 2900, 6300):
    print('  W = %5d 년: 남는 비율 %.3f' % (W, min(1.0, 160.0 / W)))
print('주기 P 의 사인파가 폭 W 이동평균 뒤에 남는 진폭 비율 = |sin(pi W/P) / (pi W/P)|')
Ps = (200, 300, 500, 1000, 2000, 4000)
Ws = (100, 300, 600, 1000, 2900)
print('  W \\ P  ' + ''.join('%8d' % P for P in Ps))
for W in Ws:
    print('  %5d  ' % W + ''.join('%8.3f' % abs(np.sinc(W / P)) for P in Ps))
print('Marcott 등(2013) 시험은 1000년 주기가 약 50% 남는다고 했다. 이동평균 폭 W 가 몇이면 P=1000 에서 0.5 가 되는가:')
Wg = np.arange(1, 1500)
r = np.abs(np.sinc(Wg / 1000.0))
iw = Wg[np.argmin(np.abs(r - 0.5))]
print('  W = %d 년 (남는 비율 %.3f). 이 W 에서 P=300 은 %.3f, P=2000 은 %.3f 남는다' % (iw, abs(np.sinc(iw / 1000.0)), abs(np.sinc(iw / 300.0)), abs(np.sinc(iw / 2000.0))))
print('  (논문 서술은 300년보다 짧으면 거의 없고 2000년보다 길면 거의 다 남는다. 이 근사는 그 취지와 같은 방향이다. 논문의 시험은 연대 오차와 표본 간격을 함께 쓴 것이라 같은 모형이 아니다.)')
print()
print('=== 계산 1-3 (3) 시연: 8.2 ka 사건 비슷한 모양(깊이 1.0 per 단위, 길이 160년)이 10 cm 혼합과 두 퇴적 속도에서 ===')
t = np.arange(0, 20000, 1.0)
sig = np.zeros_like(t); sig[(t >= 9900) & (t < 10060)] = -1.0
for lab, W in (('3.4 cm/kyr, 혼합 약 10 cm', 2941), ('1.6 cm/kyr, 혼합 약 10 cm', 6250), ('3.4 cm/kyr, 혼합 약 7.5 cm', 2206)):
    k = np.ones(W) / W
    sm = np.convolve(sig, k, mode='same')
    print('  %-34s W=%4d 년: 최저값 %.3f (원래 -1), 값이 -0.01 아래인 구간의 길이 %d 년' % (lab, W, sm.min(), int((sm < -0.01).sum())))
