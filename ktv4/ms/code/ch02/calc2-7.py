"""계산 2-7: 논문이 적은 연대 오차를 나이에 대한 비율로 바꾸고, 8.2 ka(8186 BP, 8236 b2k)에 같은 비율을 적용하면 몇 년이 되는지 본다(산술).
논문 값: GICC05 MCE 8236 b2k 에서 47 년(Walker 등 2018); WD2014 홀로세에서 나이의 0.5% 보다 정확(Sigl 등 2016, 10Be 와 IntCal13 14C 로 검증);
         AICC2012 NGRIP GICC05 절대 나이 불확실성(1시그마) 2.2% 미만(60.2 ka 까지, Veres 등 2013); EDML-NGRIP 홀로세 화산 연결 50 년(Veres 등 2013);
         EDC3 사건 길이 20%(2시그마) 이내(MIS 11 까지), 절대 나이 최대 6 ka 이내(800 ka 까지, Parrenin 등 2007); Vostok GT4 최근 110 ka 에서 ± 5 ka(Petit 등 1999);
         TALDICE-1 홀로세 초기와 마지막 이탈기 약 300 년(Buiron 등 2011 값을 Veres 등 2013 이 인용; 이 책은 Buiron 등을 읽지 못함);
         U-Th(Cheng 등 2013) 10 ka 에서 ± 10 년(2시그마, 이상적 조건). WD2014 와 GICC05: 11,595 BP 에서 24 년 차(Sigl 등 2016).
"""
rows = [('GICC05 MCE (8236 b2k)', 47, 8236, 'MCE, 95% 넘는 확률로 해석(Walker 등 2018)'),
        ('WD2014 홀로세 (나이의 0.5% 보다 정확)', 0.005 * 8236, 8236, '상한(0.5%) x 8236'),
        ('AICC2012 NGRIP/GICC05 (1시그마 2.2% 미만)', 0.022 * 8236, 8236, '60 ka 까지의 값을 8236 에 적용한 상한. 홀로세에는 과대'),
        ('AICC2012 EDML-NGRIP 홀로세 화산 연결', 50, None, '연결 하나의 불확실성'),
        ('TALDICE-1 홀로세 초기 (Buiron 등 인용)', 300, None, '홀로세 초기와 마지막 이탈기'),
        ('EDC3 절대 나이 최대 (800 ka)', 6000, 800000, '최대. 홀로세 값은 이 책이 확인 못 함'),
        ('Vostok GT4 (최근 110 ka)', 5000, 110000, '구간 전체의 ±. 홀로세 값은 아님'),
        ('U-Th 10 ka (2시그마, 이상적)', 10, 10000, '동굴 석순, 산호의 측정 오차(연대 모형 오차는 별도)')]
print('=== 계산 2-7 (1) 오차를 비율로 ===')
for nm, err, age, note in rows:
    if age: print('  %-46s ±%7.1f 년 / %7d 년 = %6.2f%%   (%s)' % (nm, err, age, 100 * err / age, note))
    else: print('  %-46s ±%7.1f 년 (나이 비율 계산 안 함)   (%s)' % (nm, err, note))
print()
print('=== 계산 2-7 (2) 8.2 ka 사건 연대에서 두 눈금의 차를 오차로 나눔 ===')
print('  WD2014 는 GICC05 보다 11,595 BP 에서 24 년 젊고(Sigl 등 2016) 두 눈금의 오차를 합친 안에 든다고 논문이 썼다. 8.2 ka 에서의 차이는 이 책이 확인하지 못했다.')
print('  GICC05 MCE 47 년과 WD2014 상한 0.5%%(%.0f 년)를 제곱합하면 %.0f 년, 선형 합하면 %.0f 년.' % (0.005 * 8236, (47 ** 2 + (0.005 * 8236) ** 2) ** 0.5, 47 + 0.005 * 8236))
print('  같은 눈금 위에 동기화된 기록끼리의 상대 연대에는 눈금의 절대 오차가 그대로 들어가지 않는 것이 동기화 눈금의 취지이다. 그러나 그 상대 오차의 크기는 이 책이 읽은 쪽에 없다.')
