# -*- coding: utf-8 -*-
"""계산 2-4: GICC05 의 최대 계수 오차(MCE)를 논문 숫자로 다시 맞춰 보고, MCE 가 가우스 오차와 어떻게 다른지 본다.
논문 값: Rasmussen 등(2007) 구간별 MCE: 2~3.8 ka 약 0.25% (구간 전체에서 5년), 3.8~6.9 ka 약 0.5%, 6.9~7.9 ka 약 2%, 7.9 ka 아래 홀로세 0.7~2%;
         8.2 ka 사건 47년, 9.3 ka 사건 70년, 프리보레알 진동 97년, 사크순바튼 테프라 10,347 b2k ± 89, 베데 테프라 12,171 ± 114, 홀로세 시작 11,703 ± 99, GI-1e 시작 14,692 ± 186.
         Walker 등(2009): 99 = Dye-3 47 + GRIP/NGRIP 52, 불명확한 층은 각각 1/2년으로 세고 MCE = (그런 특징 수)/2, 2시그마로 다룸, 진짜 나이가 95% 넘는 확률로 99년 안.
         Walker 등(2018): 8236 b2k 에서 ±47 (95% 넘는 확률). Svensson 등(2008) 더 오래된 구간: 46.9 ± 1.0 ka, 55.4 ± 1.2, 59.4 ± 1.3 (b2k).
"""
import numpy as np
print('=== 계산 2-4 (1) 구간별 백분율 MCE 로 8236 b2k 의 누적 오차를 다시 맞추기 ===')
secs = [('2~3.8 ka', 2000, 3800, 0.0025, 0.0025), ('3.8~6.9 ka', 3800, 6900, 0.005, 0.005), ('6.9~7.9 ka', 6900, 7900, 0.02, 0.02), ('7.9~8.236 ka (0.7~2%)', 7900, 8236, 0.007, 0.02)]
tot_lo = tot_hi = 0
for nm, a, b, plo, phi in secs:
    lo, hi = (b - a) * plo, (b - a) * phi
    tot_lo += lo; tot_hi += hi
    print('  %-24s 길이 %4d 년 x %.2f%%~%.2f%% = %.1f ~ %.1f 년' % (nm, b - a, plo * 100, phi * 100, lo, hi))
print('  합(0~2 ka 는 논문 발췌에 값이 없어 0으로 둠): %.1f ~ %.1f 년.  논문의 8.2 ka 사건 MCE 는 47 년, 홀로세 시작의 Dye-3 몫도 47 년.' % (tot_lo, tot_hi))
print('  47 과의 차: %.1f ~ %.1f 년. 이 차가 0~2 ka 구간의 몫이면 맞는다(그 구간의 값은 이 책이 읽은 발췌에 없다).' % (47 - tot_hi, 47 - tot_lo))
print('  2~3.8 ka 구간 검산: 1800 년 x 0.25%% = %.1f 년 (논문: 구간 전체에서 5년)' % (1800 * 0.0025))
print()
print('=== 계산 2-4 (2) 나이에 대한 비율 ===')
pts = [('8.2 ka 사건 북그리피안 경계', 8236, 47), ('9.3 ka 사건', 9300, 70), ('사크순바튼 테프라', 10347, 89), ('프리보레알 진동(약 11.4 ka 로 어림, 논문의 나이는 표에 없음)', 11400, 97), ('홀로세 시작', 11703, 99), ('베데 테프라', 12171, 114), ('GI-1e 시작', 14692, 186), ('GI-12 시작(Svensson 2008)', 46900, 1000), ('GI-15 NAAZ II', 55400, 1200), ('GI-17 시작', 59400, 1300)]
for nm, a, m in pts:
    print('  %-52s %6d b2k  MCE %4d 년  = %.2f%%' % (nm, a, m, 100 * m / a))
print('  (9.3 ka 사건의 나이는 논문에서 9350 또는 9310 b2k 라 했으므로 9300 은 어림이다. 프리보레알 진동의 나이는 이 책이 확인하지 못해 11,400 은 위치를 보이려는 어림이다.)')
print()
print('=== 계산 2-4 (3) MCE 는 가우스 오차인가: 불명확한 층이 서로 독립이라면 ===')
for nm, mce in (('8236 b2k', 47), ('홀로세 시작 Dye-3 몫', 47), ('홀로세 시작 GRIP/NGRIP 몫', 52), ('홀로세 시작 합', 99)):
    n = 2 * mce   # MCE = (불명확한 층 수)/2
    s_ind = 0.5 * np.sqrt(n)    # 각 층이 0 또는 1 년(확률 1/2)이면 표준편차 0.5 년
    print('  %-26s MCE %3d 년 -> 불명확한 층 %3d 개. 층마다 독립이면 합의 1시그마 %.1f 년, 2시그마 %.1f 년. MCE 는 그 2시그마의 %.1f 배' % (nm, mce, n, s_ind, 2 * s_ind, mce / (2 * s_ind)))
print('  두 코어 몫을 독립으로 더하면(제곱합): 홀로세 시작 MCE 로 47 과 52 를 더한 값은 %d (선형 합), 제곱합 %.1f' % (47 + 52, np.sqrt(47 ** 2 + 52 ** 2)))
print('  Walker 등(2009)은 99 를 2시그마로 다룬다고 했다 -> 1시그마 %.1f 년' % (99 / 2))
print()
print('=== 계산 2-4 (4) 시연: 불명확한 층을 각각 0 또는 1 년으로 세는 모의 (층마다 독립) ===')
rng = np.random.default_rng(20261027)
for nm, n in (('8236 b2k (불명확한 층 94개)', 94), ('11,703 b2k (198개)', 198)):
    e = rng.integers(0, 2, size=(100000, n)).sum(axis=1) - n / 2   # 1/2 년으로 센 값과의 차
    print('  %s: 오차의 표준편차 %.2f 년, 95%% 구간 ±%.1f 년, 최대 절대값 %.1f 년 (MCE %.0f)' % (nm, e.std(), np.percentile(np.abs(e), 95), np.abs(e).max(), n / 2))
print('  층마다 독립이 아니라 한 방향으로 모두 틀리면 오차가 MCE 에 닿는다. 논문의 MCE 는 그 극단을 보수적으로 잡은 값이며, Walker 등(2009)이 95% 넘는 확률로 보는 것은 그래서이다.')
